#!/home/jsc64/team-env/oracle-2026-10-30/bin/python
"""
Generates tests/goldens/slices/bridge/bridge_consts.txt (slice S2, CONTRACT 16.S2.6): for the seven zenith-float constants
(ConstantId Pi E Ln2 Ln10 Sqrt2 Phi EulerGamma) at every precision of PS, the two p-bit neighbours DOWN < c < UP and a truth
interval [TLO, THI] of c at p + 192 bits (TLO rounded down, THI rounded up). Run with ~/team-env/oracle-2026-10-30/bin/python:
    ~/team-env/oracle-2026-10-30/bin/python scripts/gen_bridge_const_goldens.py              write the golden
    ~/team-env/oracle-2026-10-30/bin/python scripts/gen_bridge_const_goldens.py --check DIR  regenerate into DIR and compare byte for byte
    ~/team-env/oracle-2026-10-30/bin/python scripts/gen_bridge_const_goldens.py --selftest   the generator's own checks

ORACLE. mpmath 1.3.0 libmp. Every directed result is settled twice, as zenith-float's scripts/gen_r14_const_goldens.py does (the
generator of zf's r14_consts.jsonl, whose Down/Up rows this file matches at the shared precisions): the round-to-nearest value
at p + 256 and at p + 512 bits, widened by one ulp of that precision, must round to one p-bit result in the mode, and the two must
agree. Each row is then checked: DOWN < TLO < THI < UP and UP - DOWN is exactly one ulp of DOWN's binade at p.
FRACTIONS SELFTEST. fraction_check re-reads every row text with Python's fractions (no mpmath): the ordering, the one-ulp width,
ends of at most p bits, and for the algebraic constants the defining sign: x^2 - 2 for Sqrt2, x^2 - x - 1 for Phi, negative at
DOWN and TLO, positive at THI and UP. It runs on freshly generated rows before writing and, with --selftest, on the committed file.
A consumer asserts that its enclosure of c contains [TLO, THI] and, for the tightness check, that its ends are DOWN and UP.
"""
import os
import sys
from fractions import Fraction

import goldlib
from mpmath import libmp as L

GENERATOR_VERSION = 1
GOLDEN_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "goldens", "slices", "bridge")
GOLDEN_NAME = "bridge_consts.txt"
PS = (1, 2, 3, 24, 53, 63, 64, 65, 100, 113, 127, 128, 129, 192, 256, 333, 512, 1000, 1024, 2048)
TRUTH_EXTRA = 192
CONSTS = (
    ("Pi", L.mpf_pi),
    ("E", L.mpf_e),
    ("Ln2", L.mpf_ln2),
    ("Ln10", L.mpf_ln10),
    ("Sqrt2", lambda prec, rnd: L.mpf_sqrt(L.from_int(2), prec, rnd)),
    ("Phi", L.mpf_phi),
    ("EulerGamma", L.mpf_euler),
)
HEADER = [
    "# zenith-bound S2 constant bridge rows, generated by scripts/gen_bridge_const_goldens.py (generator version %d)" % GENERATOR_VERSION,
    "# row: NAME P DOWN UP TLO THI ; a value is 'EXP MANT' = MANT * 2^EXP, MANT lowercase hex and odd (all values positive)",
    "# DOWN < c < UP are the p-bit neighbours of c (UP - DOWN = one ulp at p); [TLO, THI] contains c, at p + %d bits" % TRUTH_EXTRA,
    "# rows in CONSTS order (Pi E Ln2 Ln10 Sqrt2 Phi EulerGamma), then P ascending; mpmath 1.3.0 in the oracle venv",
]


class Unsettled(Exception):
    """The two oracle precisions disagree or straddle a p-bit boundary."""


def settle(fn, p, extra, rnd):
    q = p + extra
    v = fn(q, "n")
    _, _, exp, bc = v
    ulp = L.from_man_exp(1, exp + bc - q)
    lo = L.mpf_pos(L.mpf_sub(v, ulp, q + 8, "f"), p, rnd)
    hi = L.mpf_pos(L.mpf_add(v, ulp, q + 8, "c"), p, rnd)
    return lo if lo == hi else None


def directed(name, fn, p, rnd):
    a, b = settle(fn, p, 256, rnd), settle(fn, p, 512, rnd)
    if a is None or b is None or a != b:
        raise Unsettled("%s p=%d %s" % (name, p, rnd))
    return a


def enc(v):
    sign, man, exp, _ = v
    if sign != 0 or man <= 0 or man % 2 == 0:
        raise Unsettled("not a positive normalised mpf: %r" % (v,))
    return "%d %x" % (exp, man)


def check_row(name, p, down, up, tlo, thi):
    if not (L.mpf_lt(down, tlo) and L.mpf_lt(tlo, thi) and L.mpf_lt(thi, up)):
        raise Unsettled("%s p=%d: not DOWN < TLO < THI < UP" % (name, p))
    _, man, exp, bc = down
    ulp = L.from_man_exp(1, exp + bc - p)
    if L.mpf_sub(up, down) != ulp:
        raise Unsettled("%s p=%d: UP - DOWN is not one ulp" % (name, p))
    if L.mpf_pos(up, p, "n") != up or L.mpf_pos(down, p, "n") != down:
        raise Unsettled("%s p=%d: an end is wider than p bits" % (name, p))


def frac(exp, man):
    e, m = int(exp), int(man, 16)
    return Fraction(m) * (Fraction(2) ** e)


def fraction_check(lines):
    """Exact Fraction re-check of golden rows (CONTRACT 16.S2.5); independent of mpmath."""
    signs = {"Sqrt2": lambda x: x * x - 2, "Phi": lambda x: x * x - x - 1}
    n = 0
    for line in lines:
        if line.startswith("#"):
            continue
        f = line.split()
        if len(f) != 10:
            raise Unsettled("fractions: bad row %r" % line)
        name, p = f[0], int(f[1])
        down, up, tlo, thi = (frac(f[i], f[i + 1]) for i in (2, 4, 6, 8))
        if not (down < tlo < thi < up):
            raise Unsettled("fractions: %s p=%d not DOWN < TLO < THI < UP" % (name, p))
        for v, man in ((down, f[3]), (up, f[5])):
            if int(man, 16).bit_length() > p:
                raise Unsettled("fractions: %s p=%d an end is wider than p bits" % (name, p))
        k = 0
        while Fraction(2) ** (k + 1) <= down:
            k += 1
        while Fraction(2) ** k > down:
            k -= 1
        if up - down != Fraction(2) ** (k + 1 - p):
            raise Unsettled("fractions: %s p=%d UP - DOWN is not one ulp" % (name, p))
        g = signs.get(name)
        if g is not None and not (g(down) < 0 and g(tlo) < 0 and g(thi) > 0 and g(up) > 0):
            raise Unsettled("fractions: %s p=%d the defining polynomial does not change sign inside [TLO, THI]" % (name, p))
        n += 1
    return n


def rows():
    out = []
    for name, fn in CONSTS:
        for p in PS:
            down, up = directed(name, fn, p, "f"), directed(name, fn, p, "c")
            q = p + TRUTH_EXTRA
            tlo, thi = directed(name, fn, q, "f"), directed(name, fn, q, "c")
            check_row(name, p, down, up, tlo, thi)
            out.append(" ".join([name, str(p), enc(down), enc(up), enc(tlo), enc(thi)]))
    return out


def selftest():
    # pi at 2 bits: 3 <= pi < 4, so DOWN = 3 = 3 * 2^0 and UP = 4 = 1 * 2^2
    pi = dict(CONSTS)["Pi"]
    if enc(directed("Pi", pi, 2, "f")) != "0 3" or enc(directed("Pi", pi, 2, "c")) != "2 1":
        raise Unsettled("selftest: pi at 2 bits")
    # a row whose UP is two ulps above DOWN must be refused
    three, five = L.from_int(3), L.from_int(5)
    try:
        check_row("x", 2, three, five, L.from_man_exp(13, -2), L.from_man_exp(14, -2))
    except Unsettled:
        pass
    else:
        raise Unsettled("selftest: a two-ulp row was accepted")
    # fractions: sqrt2 at 2 bits: DOWN 1, UP 3/2, bracket [11/8, 23/16]; a row whose bracket misses sqrt2 must be refused
    fraction_check(["Sqrt2 2 0 1 -1 3 -3 b -4 17"])
    try:
        fraction_check(["Sqrt2 2 0 1 -1 3 -2 5 -3 b"])
    except Unsettled:
        pass
    else:
        raise Unsettled("selftest: fractions accepted a bracket that misses sqrt2")


def write_file(path):
    body = rows()
    fraction_check(body)
    goldlib.write_lines(path, HEADER + body)


def main(argv):
    goldlib.require_mpmath()
    selftest()
    # --skip-heavy is a documented no-op (bridge consts have no heavy tier); tools/goldens_regen.sh passes it to every
    # slice generator in regen-gate mode, so it is stripped wherever it appears and nothing else changes.
    argv = [a for a in argv if a != "--skip-heavy"]
    if len(argv) == 2 and argv[0] == "--check":
        os.makedirs(argv[1], exist_ok=True)
        write_file(os.path.join(argv[1], GOLDEN_NAME))
        return 1 if goldlib.check_against(argv[1], GOLDEN_DIR, [GOLDEN_NAME]) else 0
    if argv == []:
        write_file(os.path.join(GOLDEN_DIR, GOLDEN_NAME))
        return 0
    if argv == ["--selftest"]:
        with open(os.path.join(GOLDEN_DIR, GOLDEN_NAME)) as fh:
            n = fraction_check([ln.rstrip("\n") for ln in fh if ln.strip()])
        print("gen_bridge_const_goldens: fractions selftest: %d rows exact" % n)
        return 0
    raise SystemExit("usage: ~/team-env/oracle-2026-10-30/bin/python scripts/gen_bridge_const_goldens.py [--check DIR [--skip-heavy] | --selftest]")


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except Unsettled as e:
        print("gen_bridge_const_goldens: %s" % e)
        sys.exit(3)
