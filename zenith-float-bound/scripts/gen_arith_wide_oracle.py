#!/usr/bin/env python3
"""
Generates tests/goldens/slices/arith/arith_wide_rows.txt: slice S1 Ball rows at PREC 100_000 and 1_000_000 bits on
cosmology-scale inputs given as exact decimal strings (CONSTS below), read by tests/harness/slice_arith/harper_cosmo_wide.rs
through harper_oracle.rs check_row (containment of [LO, HI], tight rad <= tau*RREF, loose rad <= 2^10*RREF).
    ~/team-env/oracle-2026-10-30/bin/python scripts/gen_arith_wide_oracle.py              write the golden (inside popslot/poprun only)
    ~/team-env/oracle-2026-10-30/bin/python scripts/gen_arith_wide_oracle.py --check DIR [--skip-heavy]
    ~/team-env/oracle-2026-10-30/bin/python scripts/gen_arith_wide_oracle.py --sample DIR N   only the first N rows (the RSS proof run)
ROW: the arith_oracle_rows.txt format (scripts/gen_arith_oracle.py docstring), 25 fields. INPUTS: each decimal is rounded
DOWN to a dyadic of SHORT_BITS (128) bits ("short") or, at PREC 100_000 only, of PREC bits ("wide", exact ops only); the
radius is 0 or 2^(EXP-200) (relative 2^-200). TRUTH: exact ops (add sub mul mul_exact sqr neg abs) use gen_arith_oracle's
exact Fraction image unchanged (W = 2*PREC + 64). Inexact ops (div inv sqrt) take [LO, HI] rounded INWARD to W = 1024 bits
(written in the W field), always with a radius >= 2^-200 relative, so the inward points lie in the true image (containment
stays a valid demand) and their spread is within 2^-1024 relative of the true spread (RREF stays a sound tightness
reference; tau >= 2 absorbs the difference). Every row is cross-checked by gen_arith_oracle.cross_check (mpmath.iv at W + 64).
STREAMING: rows are written one at a time. SIZE: only the "wide" rows carry PREC-bit mantissas (a few hundred KB).
"""
import os
import resource
import sys
from fractions import Fraction

import goldlib
import gen_arith_oracle as A
from gen_ball_goldens import canon, vfrac, from_fraction, venc
from gen_ball_enclosure import rnd, sqrt_bound, ulp, RowRejected, Disagreement

GENERATOR_VERSION = 1
GOLDEN_DIR = A.GOLDEN_DIR
GOLDEN_NAME = "arith_wide_rows.txt"
SHORT_BITS = 128
REL_RAD = 200
INEXACT_W = 1024
PRECS = (100_000, 1_000_000)
RSS_CAP_KIB = 1024 * 1024

# name, exact decimal string (SI magnitudes; CODATA 2018 / Planck 2018 rounded as written: the string IS the input)
CONSTS = [
    ("planck_length_m", "1.616255e-35"),
    ("hubble_radius_m", "1.3746e26"),
    ("cosmological_constant_m-2", "1.1056e-52"),
    ("planck_mass_kg", "2.176434e-8"),
    ("observable_mass_kg", "1.5e53"),
    ("planck_constant_Js", "6.62607015e-34"),
    ("1e61", "1e61"), ("1e-61", "1e-61"),
    ("1e120", "1e120"), ("1e-120", "1e-120"),
    ("1e300", "1e300"), ("1e-300", "1e-300"),
]
# binary pairs (index into CONSTS, index, sign of B); the last three are cancellation pairs (B = -(A + A*2^-150) or B = A)
PAIRS = [(0, 1, 0), (2, 8, 0), (10, 11, 1), (3, 4, 0), (6, 7, 1), (5, 9, 0), (0, 3, 1)]
CANCEL = [1, 8, 11]

HEADER = [
    "# zenith-float-bound slice S1 wide-precision cosmology rows, generated by scripts/gen_arith_wide_oracle.py (generator version %d)" % GENERATOR_VERSION,
    "# row format: as arith_oracle_rows.txt (OP PREC W N AMID ARAD BMID BRAD LO HI RREF); W = 2*PREC + 64 exact ops, %d inexact (inward)" % INEXACT_W,
    "# inputs: " + " ".join("%s=%s" % c for c in CONSTS) + " rounded down to %d bits (wide: PREC bits)" % SHORT_BITS,
]


def dy(dec, bits, sign=0):
    v = from_fraction(rnd(Fraction(dec), bits, "Down"))
    return (sign, v[1], v[2])


def rad_of(v, mode):
    return A.ZERO if mode == 0 else canon(0, 1, v[1] - REL_RAD)


def make_inexact(op, prec, a, ar_v, b, br_v, row):
    """gen_arith_oracle.truth's inexact branch with W = INEXACT_W, then the same mpmath cross_check."""
    am, ar, bm, br = vfrac(a), vfrac(ar_v), vfrac(b), vfrac(br_v)
    w = INEXACT_W
    lo_x, hi_x = A.image(op, 0, am, ar, bm, br)
    root = op == "sqrt"

    def bound(x, up):
        return sqrt_bound(x, w, up) if root else x
    lo, hi = rnd(bound(lo_x, True), w, "Up"), rnd(bound(hi_x, False), w, "Down")
    if lo > hi:
        raise RowRejected("row %s: inward pair crosses (radius too small for W)" % row)
    fm = {"sqrt": lambda: sqrt_bound(am, w + 8, False), "div": lambda: am / bm, "inv": lambda: 1 / am}[op]()
    u = ulp(fm, prec)
    spread = max(hi - fm, fm - lo)
    rref = rnd(spread + u, A.RREF_BITS, "Up")
    A.cross_check(op, prec, 0, w, am, ar, bm, br, lo, hi, False, 0, row)
    vals = [from_fraction(lo), from_fraction(hi), from_fraction(rref)]
    return goldlib.fmt_row(op, prec, w, 0, *[venc(v) for v in (a, ar_v, b, br_v)], *[venc(v) for v in vals])


def specs():
    """(op, prec, n, a, ar, b, br) in a fixed order."""
    for prec in PRECS:
        short = [dy(d, SHORT_BITS) for _, d in CONSTS]
        for i, j, sb in PAIRS:
            a, b = short[i], (sb, short[j][1], short[j][2])
            for mode in (0, 1):
                for op in ("add", "sub", "mul"):
                    yield (op, prec, 0, a, rad_of(a, mode), b, rad_of(b, mode))
            yield ("mul_exact", prec, 0, a, rad_of(a, 1), b, A.ZERO)
            yield ("div", prec, 0, a, rad_of(a, 1), b, rad_of(b, 1))
        for k in CANCEL:
            a = short[k]
            near = from_fraction(-(vfrac(a) + vfrac(canon(0, 1, a[1] - 150))))
            for b in (near, a):
                for op in ("add", "sub"):
                    yield (op, prec, 0, a, rad_of(a, 0), b, A.ZERO)
                yield ("sub", prec, 0, a, rad_of(a, 1), b, rad_of(b, 1))
        for a in short:
            for mode in (0, 1):
                for op, n in (("sqr", 2), ("neg", 0), ("abs", 0)):
                    yield (op, prec, n, a, rad_of(a, mode), A.ZERO, A.ZERO)
            if prec == PRECS[0] or a in (short[0], short[10], short[11]):
                for op in ("sqrt", "inv"):
                    yield (op, prec, 0, a, rad_of(a, 1), A.ZERO, A.ZERO)
    prec = PRECS[0]
    wide = [dy(d, prec) for _, d in CONSTS]
    for i, j, sb in PAIRS[:3]:
        a, b = wide[i], (sb, wide[j][1], wide[j][2])
        for op in ("add", "sub", "mul"):
            yield (op, prec, 0, a, A.ZERO, b, A.ZERO)
    yield ("sqr", prec, 2, wide[1], A.ZERO, A.ZERO, A.ZERO)
    yield ("mul_exact", prec, 0, wide[0], rad_of(wide[0], 1), wide[1], A.ZERO)


def stream(path, limit):
    count = 0
    with open(path, "wb") as f:
        for line in HEADER:
            f.write((line + "\n").encode("ascii"))
        for op, prec, n, a, ar, b, br in specs():
            if limit is not None and count >= limit:
                break
            tag = "%d %s p=%d" % (count, op, prec)
            if op in ("div", "inv", "sqrt"):
                row = make_inexact(op, prec, a, ar, b, br, tag)
            else:
                row = A.make_row(op, prec, n, a, ar, b, br, row=tag)
            f.write((row + "\n").encode("ascii"))
            count += 1
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    print("gen_arith_wide_oracle: rows %d, file bytes %d, peak RSS %d KiB (cap %d)" % (count, os.path.getsize(path), peak, RSS_CAP_KIB))
    if peak > RSS_CAP_KIB:
        raise SystemExit("gen_arith_wide_oracle: peak RSS over the cap")


def main(argv):
    goldlib.require_mpmath()
    args = [x for x in argv if x != "--skip-heavy"]
    if len(args) == 2 and args[0] == "--check":
        os.makedirs(args[1], exist_ok=True)
        stream(os.path.join(args[1], GOLDEN_NAME), None)
        return 1 if goldlib.check_against(args[1], GOLDEN_DIR, [GOLDEN_NAME]) else 0
    if len(args) == 3 and args[0] == "--sample":
        os.makedirs(args[1], exist_ok=True)
        stream(os.path.join(args[1], GOLDEN_NAME), int(args[2]))
        return 0
    if args == []:
        stream(os.path.join(GOLDEN_DIR, GOLDEN_NAME), None)
        return 0
    raise SystemExit("usage: scripts/gen_arith_wide_oracle.py [--check DIR [--skip-heavy] | --sample DIR N]")


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except Disagreement as e:
        print("gen_arith_wide_oracle: mpmath.iv DISAGREES: %s" % e)
        sys.exit(3)
    except RowRejected as e:
        print("gen_arith_wide_oracle: row rejected: %s" % e)
        sys.exit(4)
