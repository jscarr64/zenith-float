#!/home/jsc64/team-env/oracle-2026-10-30/bin/python
"""Generate tests/goldens/mag_ops_review.txt: boundary rows for the Mag operations.

The expected values come from an independent big-integer oracle written for the L0a review
(Rusty's oracle.py, reproduced here): a value is M * 2^k with an infinitesimal tail delta in
{-1, 0, +1}, and the result is the least (up) or greatest (down) Mag at or above or below it. It
shares no code with the Rust crate. Usage: ~/team-env/oracle-2026-10-30/bin/python scripts/gen_review_goldens.py > tests/goldens/mag_ops_review.txt
(no mpmath is used; goldlib's oracle startup check still runs so every generator has one interpreter)

Row format (one per line): binary `OP EA MA EB MB R`, unary `OP E M R`, ulp `ulp_mag|half_ulp EXP PREC R`;
`R` is `ER MR` or the word `inf`. Zero is `0 0`.
"""
import math

import goldlib  # noqa: F401  oracle startup check at import

MIN = -(1 << 63)
MAX = (1 << 63) - 1
TOP = 1 << 63
MASK = (1 << 64) - 1


def enc(M, k, delta, up):
    if M == 0:
        return "Z"
    b = M.bit_length()
    E = b + k  # 2^(E-1) <= M*2^k < 2^E
    if delta < 0 and M & (M - 1) == 0:
        E -= 1
    if E > MAX:
        return "I" if up else f"{MAX},{MASK}"
    if E < MIN:
        return f"{MIN},{TOP}" if up else "Z"
    sh = k - E + 64
    if sh >= 0:
        m = M << sh
        rem = 0
    else:
        m, rem = divmod(M, 1 << (-sh))
    if up:
        m = m + (1 if (rem > 0 or delta > 0) else 0)
    else:
        if rem == 0 and delta < 0:
            m -= 1
    if m > MASK:
        m = TOP
        E += 1
    if E > MAX:
        return "I"
    return f"{E},{m}"


def parse(x):
    if x == "Z":
        return ("Z",)
    if x == "I":
        return ("I",)
    e, m = x.split(",")
    return ("F", int(e), int(m))


def addsub(a, b, sub):
    ea, ma = a[1], a[2]
    ka = ea - 64
    if b[0] == "Z":
        return (ma, ka, 0)
    eb, mb = b[1], b[2]
    kb = eb - 64
    if not sub and a[0] == "Z":
        return (mb, kb, 0)
    if ea < eb or (ea == eb and ma < mb):
        if sub:
            return None
        (ea, ma, ka), (eb, mb, kb) = (eb, mb, kb), (ea, ma, ka)
    gap = ea - eb
    if gap > 3000:
        return (ma, ka, -1 if sub else 1)
    return ((ma << gap) + (-mb if sub else mb), kb, 0)


def expected(op, a, b):
    a = parse(a)
    b = parse(b) if b != "-" else None
    ai = a[0] == "I"
    bi = b is not None and b[0] == "I"
    az = a[0] == "Z"
    bz = b is not None and b[0] == "Z"
    if op == "add_up":
        if ai or bi:
            return "I"
        if az and bz:
            return "Z"
        if az:
            return enc(b[2], b[1] - 64, 0, True)
        return enc(*addsub(a, b, False), True)
    if op in ("mul_up", "mul_lower"):
        up = op == "mul_up"
        if ai or bi:
            return "I" if up else "Z"
        if az or bz:
            return "Z"
        return enc(a[2] * b[2], a[1] + b[1] - 128, 0, up)
    if op in ("div_up", "div_lower"):
        up = op == "div_up"
        if ai or bi or bz:
            return "I" if up else "Z"
        if az:
            return "Z"
        S = 140
        Q, R = divmod(a[2] << S, b[2])
        return enc(Q, (a[1] - 64) - (b[1] - 64) - S, 1 if R else 0, up)
    if op == "sub_lower":
        if ai or bi or az:
            return "Z"
        if bz:
            return enc(a[2], a[1] - 64, 0, False)
        if (a[1], a[2]) <= (b[1], b[2]):
            return "Z"
        M, k, d = addsub(a, b, True)
        if d == 0 and M <= 0:
            return "Z"
        return enc(M, k, d, False)
    raise SystemExit("bad op " + op)


def ulp(op, e, p):
    field = e - p + 1 if op == "ulp_mag" else e - p
    if field > MAX:
        return "I"
    if field < MIN:
        return f"{MIN},{TOP}"
    return f"{field},{TOP}"


def show(x):
    if x == "Z":
        return "0 0"
    if x == "I":
        return "inf"
    return x.replace(",", " ")


def mag(e, m):
    return f"{e},{m}"


rows = []


def binary(op, a, b):
    rows.append(f"{op} {show(a)} {show(b)} {show(expected(op, a, b))}")


print("# zenith-bound Mag review boundary rows, generated by scripts/gen_review_goldens.py (independent big-integer oracle)")
print("# binary: OP EA MA EB MB R ; ulp: OP EXP PREC R ; R is 'ER MR' or the word inf; value = mant * 2^(exp - 64); zero is '0 0'")

# sub_lower at exponent gap 191 (the sub_wide shift-128 boundary) and at the 64/127 boundaries
for a, b in [
    (mag(191, 0xC000000000000000), mag(0, 0xFFFFFFFFFFFFFFF0)),
    (mag(191, TOP), mag(0, MASK)),
    (mag(190, TOP), mag(0, MASK)),
    (mag(192, TOP), mag(0, MASK)),
    (mag(64, TOP), mag(0, MASK)),
    (mag(65, MASK), mag(0, MASK)),
    (mag(127, MASK), mag(0, TOP)),
]:
    binary("sub_lower", a, b)

# division whose remainder is exactly 1 or mb - 1 (round-up must see a nonzero remainder of 1)
mb = 14683125255737118537
ma = 13003197457353784699
assert ((ma << 64) % mb) == 1
# a mirror row whose remainder is mb' - 1: the first odd mb' below 2^64 whose (-1/2^64) mod mb' is >= 2^63
mb2 = MASK
while True:
    mb2 -= 2
    ma2 = (-pow(1 << 64, -1, mb2)) % mb2
    if ma2 >= TOP:
        break
assert ((ma2 << 64) % mb2) == mb2 - 1
rem_rows = [(mag(5, ma), mag(3, mb)), (mag(5, ma2), mag(3, mb2))]
for ea, eb in [(5, 3), (MIN + 64, MIN), (MAX, 0), (MIN, MAX), (MAX, MIN)]:
    for a, b in rem_rows:
        a = mag(ea, int(a.split(",")[1]))
        b = mag(eb, int(b.split(",")[1]))
        binary("div_up", a, b)
        binary("div_lower", a, b)

# add_up and sub_lower around the alignment boundaries
gaps = [62, 63, 64, 65, 66, 126, 127, 128, 129, 130, 190, 191, 192, 193]
pairs = [
    (TOP, TOP),
    (TOP, MASK),
    (TOP + 1, TOP + 1),
    (0xC000000000000000, MASK - 1),
    (MASK, TOP),
    (MASK, MASK),
]
for base in (MIN + 200, 0, MAX - 1):
    for g in gaps:
        for ma_, mb_ in pairs:
            a = mag(base, ma_)
            b = mag(base - g, mb_)
            binary("sub_lower", a, b)
            binary("add_up", a, b)

# mul carry rows: the product of m*m rounds through 2^64, at the exponent limits
m = 0xB504F333F9DE6484
for ea, eb in [(0, 0), (MIN, -1), (MIN, 0), (MIN, 1), (MAX, -1), (MAX, 0), (MAX, 1), (MIN, MAX), (MAX, MIN), (MIN, MIN + 1)]:
    a = mag(ea, m)
    b = mag(eb, m)
    binary("mul_up", a, b)
    binary("mul_lower", a, b)

# ulp_mag and half_ulp at the zenith-float exponent limits and large precisions
I32MIN, I32MAX = -(1 << 31), (1 << 31) - 1
for e in (I32MIN - 1, I32MIN, I32MIN + 1, I32MAX - 1, I32MAX, I32MAX + 1):
    for p in (1, 2, 24, 53, (1 << 31) - 1, 1 << 31, (1 << 32) - 1):
        for op in ("ulp_mag", "half_ulp"):
            rows.append(f"{op} {e} {p} {show(ulp(op, e, p))}")

print("\n".join(rows))
