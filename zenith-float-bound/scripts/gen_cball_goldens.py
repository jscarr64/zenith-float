"""
Generates tests/goldens/slices/cball/cball_rows.txt (CONTRACT 16.CB.10): mpmath.mpc POINT references for the CBall ops add, sub, mul, sqr, abs
and div, plus per-part first-order radii RREF for the tightness factors. Run with ~/team-env/oracle-2026-10-30/bin/python:
    scripts/gen_cball_goldens.py              write tests/goldens/slices/cball/cball_rows.txt
    scripts/gen_cball_goldens.py --check DIR  regenerate into DIR (never tests/goldens) and compare byte for byte
    scripts/gen_cball_goldens.py --selftest   the generator's own checks
--skip-heavy may follow any of these and is a documented no-op: cball has no heavy tier, but tools/goldens_regen.sh passes it to every
generator in gate mode (as gen_la_goldens.py takes it).

REFERENCES. For each row the input rectangles are A = [ARE +- ARER] x [AIM +- AIMR] (and B likewise). Three sample points are taken: the midpoints
(A.mid, B.mid), the low corner of A with the high corner of B, and the high corner of A with the low corner of B (unary ops: mid, low corner, high
corner). f is evaluated with mpmath.mpc at W = 4*PREC + 64 bits (round to nearest); the inputs are exact at W. A consumer asserts that its result
CONTAINS each reference (the rounding of a reference at W bits is far below any radius the op can produce at PREC). abs references have IM = 0.

RREF (per part, rounded up to 64 bits) = sum over input parts x of |d f_part / d x| * r_x at the midpoints, plus U = 2^(e - PREC), e the binade
exponent (2^(e-1) <= v < 2^e) of the largest intermediate term v of that part (mul/sqr: the products; add/sub: the result part; abs/div: |f|);
U = 0 when every term is 0. div rows are drawn with every divisor radius <= |B.mid|/16, so d = |B|^2 is clear of 0 by more than half its value.
"""
