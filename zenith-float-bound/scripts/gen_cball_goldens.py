import os
import sys
import time
from fractions import Fraction

import goldlib
from gen_ball_goldens import canon, vfrac, from_fraction, venc

GENERATOR_VERSION = 1
GOLDEN_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "goldens", "slices", "cball")
GOLDEN_NAME = "cball_rows.txt"
OPS = ("add", "sub", "mul", "sqr", "abs", "div")
UNARY = ("sqr", "abs")
PS = (1, 2, 53, 64, 113)
ROWS_PER = 2
RREF_BITS = 64
EXP_BAND = 8

HEADER = [
    "# zenith-bound slice CB gold rows, generated by scripts/gen_cball_goldens.py (generator version %d)" % GENERATOR_VERSION,
    "# row: OP PREC W ARE ARER AIM AIMR [BRE BRER BIM BIMR] RREF_RE RREF_IM R1RE R1IM R2RE R2IM R3RE R3IM ; unary ops (sqr abs) have no B",
    "# a value is 'SIGN EXP MANT': value = (-1)^SIGN * MANT * 2^(EXP - bitlen(MANT)), MANT lowercase hex and odd, zero is '0 0 0'",
    "# mids have at most PREC bits, radii at most 4 bits; R1..R3 = f at (mid, mid), (A low corner, B high corner), (A high corner, B low corner)",
    "# references: mpmath.mpc at W = 4*PREC + 64 bits, nearest; RREF: first-order radius per part plus one PREC ulp of the largest term, up to 64 bits",
    "# rows in generation order (OP order above, PREC, draw); draws: goldlib.SplitMix64 from stream_seed(16, 1)",
    "# generated in the oracle venv (mpmath 1.3.0); see scripts/README.md",
]


class Rng:
    def __init__(self, seed):
        self.g = goldlib.SplitMix64(seed)

    def below(self, n):
        return self.g.next() % n


def pow2(e):
    return Fraction(1 << e) if e >= 0 else Fraction(1, 1 << -e)


def binade(v):
    """e with 2^(e-1) <= |v| < 2^e, for a nonzero Fraction."""
    a = abs(v)
    e = a.numerator.bit_length() - a.denominator.bit_length()
    while pow2(e) <= a:
        e += 1
    while pow2(e - 1) > a:
        e -= 1
    return e


def ulp_term(terms, prec):
    nz = [t for t in terms if t != 0]
    return pow2(binade(max(abs(t) for t in nz)) - prec) if nz else Fraction(0)


def draw_mid(rng, prec, exp_lo=-EXP_BAND, exp_hi=EXP_BAND, allow_zero=True):
    if allow_zero and rng.below(8) == 0:
        return (0, 0, 0)
    k = 1 + rng.below(min(prec, 24))
    m = (1 << (k - 1)) | rng.below(1 << (k - 1)) | 1 if k > 1 else 1
    e = exp_lo + rng.below(exp_hi - exp_lo + 1)
    return canon(rng.below(2), m, e - m.bit_length())


def draw_rad(rng, prec, mid):
    c = rng.below(5)
    if c == 0:
        return (0, 0, 0)
    base = mid[1] if mid[2] else 0
    off = (prec + 1, prec, prec - 3, 20, 2)[c] if c < 5 else 2
    m = 1 + rng.below(15)
    return canon(0, m, base - off - m.bit_length())


def mpc_of(re, im):
    from mpmath import mpc, mpf
    return mpc(mpf(re.numerator) / re.denominator, mpf(im.numerator) / im.denominator)


def enc_mpf(x):
    from mpmath import mpf
    sign, man, exp, _ = mpf(x)._mpf_
    v = Fraction(int(man)) * pow2(int(exp))
    return venc(from_fraction(-v if sign else v))


def apply(op, a, b):
    from mpmath import mpc, sqrt
    if op == "add":
        return a + b
    if op == "sub":
        return a - b
    if op == "mul":
        return a * b
    if op == "div":
        return a / b
    if op == "sqr":
        return a * a
    return mpc(sqrt(a.real * a.real + a.imag * a.imag), 0)


def rref(op, prec, A, B):
    (x, rx, y, ry) = A
    if op in ("add", "sub"):
        (u, ru, v, rv) = B
        sre = x + u if op == "add" else x - u
        sim = y + v if op == "add" else y - v
        return (rx + ru + ulp_term([sre], prec), ry + rv + ulp_term([sim], prec))
    if op == "mul":
        (u, ru, v, rv) = B
        re = abs(u) * rx + abs(x) * ru + abs(v) * ry + abs(y) * rv + ulp_term([x * u, y * v], prec)
        im = abs(v) * rx + abs(x) * rv + abs(u) * ry + abs(y) * ru + ulp_term([x * v, y * u], prec)
        return (re, im)
    if op == "sqr":
        re = 2 * abs(x) * rx + 2 * abs(y) * ry + ulp_term([x * x, y * y], prec)
        im = 2 * abs(y) * rx + 2 * abs(x) * ry + ulp_term([2 * x * y], prec)
        return (re, im)
    if op == "abs":
        n2 = x * x + y * y
        if n2 == 0:
            return (rx + ry, Fraction(0))
        from mpmath import mp, mpf, sqrt
        n = sqrt(mpf(n2.numerator) / n2.denominator)
        g = (abs(x) * rx + abs(y) * ry)
        lin = mpf(g.numerator) / g.denominator / n
        return (to_frac_up(lin) + pow2(binade(to_frac_up(n)) - prec), Fraction(0))
    (u, ru, v, rv) = B
    from mpmath import mpf
    d = u * u + v * v
    qre = (x * u + y * v) / d
    qim = (y * u - x * v) / d
    inv_b = 1 / sqrt_up(d)
    qabs = sqrt_up(qre * qre + qim * qim)
    lin = inv_b * (rx + ry) + qabs * inv_b * (ru + rv)
    U = ulp_term([qre, qim], prec)
    return (lin + U, lin + U)


def to_frac_up(x):
    from mpmath import mpf
    sign, man, exp, _ = mpf(x)._mpf_
    v = Fraction(int(man)) * pow2(int(exp))
    v = -v if sign else v
    return v + abs(v) * pow2(-60)


def sqrt_up(f):
    from mpmath import mpf, sqrt
    return to_frac_up(sqrt(mpf(f.numerator) / f.denominator))


def round_up64(f):
    if f == 0:
        return Fraction(0)
    return goldlib.round_fraction(f, RREF_BITS, "Up")[0]


def corners(R, lo):
    (x, rx, y, ry) = R
    return (x - rx, y - ry) if lo else (x + rx, y + ry)


def make_row(op, prec, a, b):
    from mpmath import mp
    w = 4 * prec + 64
    A = tuple(vfrac(t) for t in a)
    B = tuple(vfrac(t) for t in b) if b is not None else None
    if op == "div":
        if B[0] == 0 and B[2] == 0:
            return None
        bm = max(abs(B[0]), abs(B[2]))
        if 16 * B[1] > bm or 16 * B[3] > bm:
            return None
    mp.prec = w
    pts = [((A[0], A[2]), (B[0], B[2]) if B else None),
           (corners(A, True), corners(B, False) if B else None),
           (corners(A, False), corners(B, True) if B else None)]
    refs = []
    for pa, pb in pts:
        za = mpc_of(*pa)
        zb = mpc_of(*pb) if pb is not None else None
        r = apply(op, za, zb)
        refs += [enc_mpf(r.real), enc_mpf(r.imag)]
    rre, rim = rref(op, prec, A, B)
    fields = [op, prec, w] + [venc(t) for t in a] + ([venc(t) for t in b] if b is not None else [])
    fields += [venc(from_fraction(round_up64(rre))), venc(from_fraction(round_up64(rim)))] + refs
    return goldlib.fmt_row(*fields)


def draw_box(rng, prec):
    re = draw_mid(rng, prec)
    im = draw_mid(rng, prec)
    return (re, draw_rad(rng, prec, re), im, draw_rad(rng, prec, im))


def stream_rows(out):
    base = goldlib.stream_seed(16, 1)
    n = 0
    t0 = time.monotonic()
    for oi, op in enumerate(OPS):
        for prec in PS:
            rng = Rng(goldlib.splitmix64(base ^ ((oi << 32) | prec)))
            got = 0
            tries = 0
            while got < ROWS_PER:
                tries += 1
                if tries > 200:
                    raise SystemExit("gen_cball_goldens: %s p=%d: too many redraws" % (op, prec))
                t1 = time.monotonic()
                a = draw_box(rng, prec)
                b = draw_box(rng, prec) if op not in UNARY else None
                row = make_row(op, prec, a, b)
                if row is None:
                    continue
                out.write(row + "\n")
                out.flush()
                got += 1
                n += 1
                print("progress: op=%s case=p%d-%d tier=gate row_s=%.3f elapsed_s=%.3f" % (op, prec, got, time.monotonic() - t1, time.monotonic() - t0), flush=True)
    for op, prec, a in extra_rows():
        t1 = time.monotonic()
        out.write(make_row(op, prec, a, None) + "\n")
        out.flush()
        n += 1
        print("progress: op=%s case=p%d-extra tier=gate row_s=%.3f elapsed_s=%.3f" % (op, prec, time.monotonic() - t1, time.monotonic() - t0), flush=True)
    return n


def extra_rows():
    """Hand-picked rows appended after the drawn stream (the drawn rows stay byte-identical).
    sqr p=53, A = 1 + (0 +- 2)i: a WIDE imaginary radius with an exact real part, so the 16.CB.10 second-order term
    rad(im)^2 = 4 dominates the re part (RREF_re is one ulp) and a sqr reference without it cannot cover re = 1 - [0, 4]
    (Spence, 2026-10-25).
    sqr p=53, A = (0 +- 2) + (0 +- 2)i: both radii nonzero and both mids 0, so RREF is 0 in both parts; the im part
    rests on the second-order term 2*rad(re)*rad(im) = 8 alone and the re part on rad(re)^2 + rad(im)^2 = 8
    (Spence cball follow-up, 2026-10-25)."""
    zero = (0, 0, 0)
    return [("sqr", 53, (canon(0, 1, 0), zero, zero, canon(0, 1, 1))),
            ("sqr", 53, (zero, canon(0, 1, 1), zero, canon(0, 1, 1)))]


def write_file(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="ascii", newline="\n") as out:
        for h in HEADER:
            out.write(h + "\n")
        n = stream_rows(out)
    print("rows %d, file bytes %d" % (n, os.path.getsize(path)))


def selftest():
    from mpmath import mp
    one, half, zero = canon(0, 1, 0), canon(0, 1, -1), (0, 0, 0)
    # (1+i) * (1-i) = 2 at every sample point's midpoint; RREF exact parts: re terms 1,1 -> U = 2^(1-8)
    row = make_row("mul", 8, (one, zero, one, zero), (one, zero, canon(1, 1, 0), zero))
    f = row.split(" ")
    if f[-18:-15] != ["0", "2", "1"] or f[-15:-12] != ["0", "0", "0"]:
        raise SystemExit("gen_cball_goldens selftest: (1+i)(1-i) reference %s" % f[-18:-12])
    if rref("mul", 8, (Fraction(1), Fraction(0), Fraction(1), Fraction(0)), (Fraction(1), Fraction(0), Fraction(-1), Fraction(0))) != (pow2(-7), pow2(-7)):
        raise SystemExit("gen_cball_goldens selftest: mul RREF hand value")
    if rref("add", 8, (Fraction(1), Fraction(1, 2), Fraction(0), Fraction(0)), (Fraction(1), Fraction(1, 2), Fraction(0), Fraction(0))) != (1 + pow2(-6), 0):
        raise SystemExit("gen_cball_goldens selftest: add RREF hand value")
    if make_row("div", 8, (one, zero, zero, zero), (one, half, zero, zero)) is not None:
        raise SystemExit("gen_cball_goldens selftest: a wide divisor was not rejected")
    # |3+4i| = 5
    row = make_row("abs", 8, (canon(0, 3, 0), zero, canon(0, 1, 2), zero), None)
    if row.split(" ")[-18:-12] != ["0", "3", "5", "0", "0", "0"]:
        raise SystemExit("gen_cball_goldens selftest: |3+4i|")
    # --skip-heavy is a no-op (no heavy tier): stripped wherever it appears, nothing else changes
    if strip_skip_heavy(["--check", "D", "--skip-heavy"]) != ["--check", "D"] or strip_skip_heavy(["--skip-heavy"]) != []:
        raise SystemExit("gen_cball_goldens selftest: --skip-heavy not stripped")
    if strip_skip_heavy(["--selftest"]) != ["--selftest"]:
        raise SystemExit("gen_cball_goldens selftest: argv changed without --skip-heavy")
    print("gen_cball_goldens selftest: ok")


def strip_skip_heavy(argv):
    """Drop --skip-heavy (documented no-op: cball has no heavy tier; tools/goldens_regen.sh passes it in gate mode)."""
    return [a for a in argv if a != "--skip-heavy"]


def main(argv):
    goldlib.require_mpmath()
    selftest()
    argv = strip_skip_heavy(argv)
    if len(argv) == 2 and argv[0] == "--check":
        os.makedirs(argv[1], exist_ok=True)
        write_file(os.path.join(argv[1], GOLDEN_NAME))
        return 1 if goldlib.check_against(argv[1], GOLDEN_DIR, [GOLDEN_NAME]) else 0
    if argv == []:
        write_file(os.path.join(GOLDEN_DIR, GOLDEN_NAME))
        return 0
    if argv == ["--selftest"]:
        return 0
    raise SystemExit("usage: scripts/gen_cball_goldens.py [--check DIR | --selftest] [--skip-heavy]")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
