"""
Generates tests/goldens/slices/carlson/lambertw_rows.txt (CONTRACT 16.S4b.3): rigorous Lambert W brackets for Ball::lambert_w0 and
Ball::lambert_wm1 (16.S4b.1, 16.S4b.2). Run with ~/.local/oracle-venv/bin/python inside a popslot memory scope:
    scripts/gen_carlson_goldens.py              write tests/goldens/slices/carlson/lambertw_rows.txt
    scripts/gen_carlson_goldens.py --check DIR  regenerate into DIR (never tests/goldens) and compare byte for byte
    scripts/gen_carlson_goldens.py --selftest   the generator's own checks
--skip-heavy may follow any of these and is a documented no-op (no heavy tier; tools/goldens_regen.sh passes it in gate mode).

ORACLE. For an input ball X = XM +- XR (XR exact; XR 'inf' is the all-reals ball) the expected outcome follows 16.S4b.2:
  domain    BoundError::Domain
  allreals  Ok(all reals)
  ok        Ok(ball) that must contain [LLO, HHI]: [LLO, LHI] brackets the least value of W over the clipped input and
            [HLO, HHI] the greatest. Each bracket is python-flint arb lambertw (branch 0 or -1) at PREC + 128 bits (doubled until
            finite next to -1/e), read back
            as the exact dyadic lower()/upper() of the arb ball; a clipped end is exactly -1 (LLO = LHI = -1 or HLO = HHI = -1).
            mpmath.lambertw at PREC + 256 bits (more near -1/e) must lie inside every bracket, or the generator refuses to write.
  TB        the 16.S4b.3 tightness bound: 4 (HHI - LLO) + 2 ulp, ulp = 2^(e - PREC) for the binade exponent e of
            max(|LLO|, |HHI|) (2^(e-1) <= v < 2^e), rounded up to 64 bits; 0 when LLO = HHI = 0.
Domain decisions (x >= -1/e) are made rigorously with arb (x e + 1 against 0 at doubling precision; -1/e is not dyadic).
Rows are streamed to disk one by one (flush per row). Values are integer pairs, never Fractions: inputs reach 2^(2^62 - 1).
"""
