import os
import sys
import time

import goldlib

GENERATOR_VERSION = 1
GOLDEN_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "goldens", "slices", "carlson")
GOLDEN_NAME = "lambertw_rows.txt"
GUARD = 128          # arb bracket precision is PREC + GUARD
MP_GUARD = 256       # mpmath cross-check precision is PREC + MP_GUARD
TB_BITS = 64
EXPONENT_MAX = (1 << 62) - 1
PRECS = (1, 2, 53, 64, 113, 256, 1024, 4096)
POLICIES = ("strict", "clip")

HEADER = [
    "# zenith-float-bound slice S4b Lambert W gold rows, generated by scripts/gen_carlson_goldens.py (generator version %d)" % GENERATOR_VERSION,
    "# row: BRANCH POLICY PREC XM XR OUT [LLO LHI HLO HHI TB] ; BRANCH w0|wm1, POLICY strict|clip, OUT ok|domain|allreals, XR 'inf' = all reals",
    "# a value is 'SIGN EXP MANT': value = (-1)^SIGN * MANT * 2^(EXP - bitlen(MANT)), MANT lowercase hex and odd, zero is '0 0 0'",
    "# ok: the result must contain [LLO, HHI]; [LLO, LHI] and [HLO, HHI] are arb lambertw brackets at PREC + 128 bits (mpmath at",
    "# PREC + 256 checked inside), a clipped end is exactly -1; TB = 4 (HHI - LLO) + 2 ulp(max(|LLO|, |HHI|), PREC), up to 64 bits",
    "# rows in the fixed order of rows() in the generator; generated in the oracle venv (python-flint 0.9.0, mpmath 1.3.0)",
]


# ---- dyadics (m, t): value m * 2^t, m a signed int -----------------------------------------------------------------------------
def dy(m, t=0):
    if m == 0:
        return (0, 0)
    while m % 2 == 0:
        m //= 2
        t += 1
    return (m, t)


def dy_add(a, b):
    if a[0] == 0:
        return b
    if b[0] == 0:
        return a
    t = min(a[1], b[1])
    if max(a[1], b[1]) - t > 1 << 20:
        raise SystemExit("gen_carlson_goldens: dy_add exponent gap too large (%d, %d)" % (a[1], b[1]))
    return dy((a[0] << (a[1] - t)) + (b[0] << (b[1] - t)), t)


def dy_neg(a):
    return (-a[0], a[1])


def dy_cmp(a, b):
    if a[0] == 0 or b[0] == 0 or (a[0] < 0) != (b[0] < 0):
        return ((a[0] > 0) - (a[0] < 0)) - ((b[0] > 0) - (b[0] < 0)) if (a[0] < 0) != (b[0] < 0) or a[0] == 0 or b[0] == 0 else 0
    d = dy_add(a, dy_neg(b))[0]
    return (d > 0) - (d < 0)


def binade(a):
    """e with 2^(e-1) <= |a| < 2^e for a nonzero dyadic."""
    return abs(a[0]).bit_length() + a[1]


def round_up_bits(a, bits):
    """Least dyadic >= a (a > 0) with at most `bits` mantissa bits."""
    m, t = a
    if m <= 0:
        raise SystemExit("gen_carlson_goldens: round_up_bits of a non-positive value")
    extra = m.bit_length() - bits
    if extra <= 0:
        return a
    q = m >> extra
    if q << extra != m:
        q += 1
    return dy(q, t + extra)


def venc(a):
    m, t = a
    if m == 0:
        return "0 0 0"
    s = 1 if m < 0 else 0
    m = abs(m)
    return "%d %d %x" % (s, t + m.bit_length(), m)


# ---- arb / mpmath --------------------------------------------------------------------------------------------------------------
def arb_of(a):
    from flint import arb, ctx
    m, t = a
    saved = ctx.prec
    ctx.prec = max(saved, abs(m).bit_length() + 16)
    v = arb(m) * (arb(2) ** t)
    ctx.prec = saved
    if not v.is_exact():
        raise SystemExit("gen_carlson_goldens: input %r is not exact in arb" % (a,))
    return v


def dy_of_arb(v):
    if not v.is_exact():
        raise SystemExit("gen_carlson_goldens: arb endpoint is not exact")
    m, t = v.man_exp()
    return dy(int(m), int(t))


def inside(x):
    """x >= -1/e, decided rigorously."""
    from flint import arb, ctx
    if x[0] >= 0:
        return True
    p = 128
    while True:
        ctx.prec = p
        s = arb_of(x) * arb(1).exp() + 1
        if s > 0:
            return True
        if s < 0:
            return False
        p *= 2
        if p > 1 << 20:
            raise SystemExit("gen_carlson_goldens: undecided domain for %r" % (x,))


def bracket(branch, x, prec):
    """(lo, hi) exact dyadics with lo <= W_branch(x) <= hi, arb at prec + GUARD; mpmath at prec + MP_GUARD must lie inside."""
    from flint import ctx
    import mpmath
    if x[0] == 0 and branch == "w0":
        return (0, 0), (0, 0)
    k = 0 if branch == "w0" else -1
    wp = prec + GUARD
    while True:   # near the branch point -1/e arb needs more bits to separate x from -1/e; a tighter bracket is still rigorous
        ctx.prec = wp
        w = arb_of(x).lambertw(branch=k)
        if w.is_finite():
            break
        wp *= 2
        if wp > 1 << 16:
            raise SystemExit("gen_carlson_goldens: arb lambertw not finite at %r" % (x,))
    lo, hi = dy_of_arb(w.lower()), dy_of_arb(w.upper())
    mpmath.mp.prec = max(prec + MP_GUARD, wp + GUARD, abs(x[0]).bit_length() + MP_GUARD)   # x itself must convert exactly
    v = mpmath.lambertw(mpmath.ldexp(mpmath.mpf(x[0]), x[1]), k)
    if v.imag != 0:
        raise SystemExit("gen_carlson_goldens: mpmath lambertw is complex at %r" % (x,))
    sign, man, exp, _ = mpmath.mpf(v.real)._mpf_
    mv = dy(-int(man) if sign else int(man), int(exp))
    if dy_cmp(lo, mv) > 0 or dy_cmp(mv, hi) > 0:
        raise SystemExit("gen_carlson_goldens: REFUSING: mpmath %r is outside the arb bracket [%r, %r] at %r" % (mv, lo, hi, x))
    return lo, hi


MINUS_ONE = (-1, 0)


def outcome(branch, policy, xm, xr, prec):
    """('domain',) / ('allreals',) / ('ok', (llo, lhi), (hlo, hhi)) per 16.S4b.2."""
    strict = policy == "strict"
    if xr is None:
        return ("domain",) if strict else ("allreals",)
    lo, hi = dy_add(xm, dy_neg(xr)), dy_add(xm, xr)
    if branch == "w0":
        if inside(lo):
            return ("ok", bracket("w0", lo, prec), bracket("w0", hi, prec))
        if strict or not inside(hi):
            return ("domain",)
        return ("ok", (MINUS_ONE, MINUS_ONE), bracket("w0", hi, prec))
    if hi[0] >= 0:
        return ("domain",) if strict else ("allreals",)
    if inside(lo):
        return ("ok", bracket("wm1", hi, prec), bracket("wm1", lo, prec))
    if strict or not inside(hi):
        return ("domain",)
    return ("ok", bracket("wm1", hi, prec), (MINUS_ONE, MINUS_ONE))


def tight(llo, hhi, prec):
    w = dy_add(hhi, dy_neg(llo))
    if w[0] < 0:
        raise SystemExit("gen_carlson_goldens: HHI < LLO")
    big = [binade(v) for v in (llo, hhi) if v[0] != 0]
    tb = dy(4 * w[0], w[1])
    if big:
        tb = dy_add(tb, dy(1, max(big) - prec + 1))
    return round_up_bits(tb, TB_BITS) if tb[0] else tb


def make_row(branch, policy, prec, xm, xr):
    o = outcome(branch, policy, xm, xr, prec)
    head = "%s %s %d %s %s %s" % (branch, policy, prec, venc(xm), "inf" if xr is None else venc(xr), o[0])
    if o[0] != "ok":
        return head
    (llo, lhi), (hlo, hhi) = o[1], o[2]
    return "%s %s %s %s %s %s" % (head, venc(llo), venc(lhi), venc(hlo), venc(hhi), venc(tight(llo, hhi, prec)))


def near_inv_e(bits, up):
    """A `bits`-bit dyadic next to -1/e: the floor (outside) or floor + 1 ulp (inside) of an arb midpoint of -1/e."""
    from flint import arb, ctx
    ctx.prec = bits + 64
    m, t = (-(arb(-1).exp())).mid().man_exp()
    m, t = int(m), int(t)
    shift = (-m).bit_length() - bits
    q = m >> shift
    if up:
        q += 1
    return dy(q, t + shift)


def rows():
    """The fixed row list: (branch, precs, xm, xr), xr None for the all-reals ball."""
    z = (0, 0)
    out = []
    w0_points = [z, dy(1, -1000), dy(-1, -1000), dy(1, -(1 << 40)), dy(-1, -(1 << 40)), dy(1), dy(-1, -2), dy(-3, -3),
                 dy(87, -5), dy(89, -5), dy(3), dy(4), dy((1 << 60) + 1, -58), dy((1 << 60) - 1, -58), dy(10), dy(1000),
                 dy(1, 100), dy(1, 1 << 40), dy(1, EXPONENT_MAX - 1), dy((1 << 64) - 1, EXPONENT_MAX - 64)]
    wm1_points = [dy(-1, -2), dy(-3, -3), dy(-13, -5), dy(-1, -10), dy(-1, -1000), dy(-1, -(1 << 40)),
                  dy(-1, -(EXPONENT_MAX - 10))]
    for x in w0_points:
        out.append(("w0", PRECS, x, z))
    for x in wm1_points:
        out.append(("wm1", PRECS, x, z))
    # both sides of -1/e and the decision boundary, rounded at several widths
    for bits in (8, 64, 150, 200, 300):
        for up in (True, False):
            x = near_inv_e(bits, up)
            out.append(("w0", (1, 53, 256), x, z))
            out.append(("wm1", (1, 53, 256), x, z))
    # wide balls
    wide = [("w0", dy(-1, -1), dy(1, -2)), ("w0", dy(1), dy(1, -1)), ("w0", z, dy(1, -10)), ("w0", dy(10), dy(8)),
            ("w0", z, dy(1)), ("w0", dy(-1), dy(1, -2)), ("w0", dy(1, 70), dy(1, 69)), ("w0", dy(-5, -4), dy(1, -4)),
            ("wm1", dy(-1, -2), dy(1, -4)), ("wm1", dy(-1, -1), dy(1, -2)), ("wm1", dy(-1, -1), dy(3, -3)),
            ("wm1", dy(-1, -10), dy(1, -10)), ("wm1", dy(-1, -10), dy(1, -11)), ("wm1", dy(-1, -1), dy(1, -4)),
            ("wm1", dy(-5, -4), dy(1, -4))]
    for br, xm, xr in wide:
        out.append((br, (1, 53, 113, 1024), xm, xr))
    for br in ("w0", "wm1"):
        out.append((br, (1, 53), z, None))
    return out


def stream_rows(out):
    n = 0
    t0 = time.monotonic()
    for br, precs, xm, xr in rows():
        for prec in precs:
            for pol in POLICIES:
                t1 = time.monotonic()
                out.write(make_row(br, pol, prec, xm, xr) + "\n")
                out.flush()
                n += 1
                print("progress: br=%s pol=%s prec=%d row_s=%.3f elapsed_s=%.3f" % (br, pol, prec, time.monotonic() - t1, time.monotonic() - t0), flush=True)
    return n


def write_file(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="ascii", newline="\n") as out:
        for h in HEADER:
            out.write(h + "\n")
        n = stream_rows(out)
    print("rows %d, file bytes %d" % (n, os.path.getsize(path)))


def selftest():
    if make_row("w0", "strict", 8, (0, 0), (0, 0)) != "w0 strict 8 0 0 0 0 0 0 ok" + " 0 0 0" * 5:
        raise SystemExit("gen_carlson_goldens selftest: W0(0)")
    lo, hi = bracket("w0", dy(1), 53)   # W0(1) = 0.56714...
    if dy_cmp(lo, dy(9, -4)) <= 0 or dy_cmp(hi, dy(37, -6)) >= 0 or dy_cmp(dy_add(hi, dy_neg(lo)), dy(1, -150)) >= 0:
        raise SystemExit("gen_carlson_goldens selftest: W0(1) bracket %r %r" % (lo, hi))
    lo, hi = bracket("wm1", dy(-1, -2), 53)   # W-1(-1/4) = -2.15329...
    if dy_cmp(lo, dy(-69, -5)) <= 0 or dy_cmp(hi, dy(-275, -7)) >= 0:
        raise SystemExit("gen_carlson_goldens selftest: W-1(-1/4) bracket %r %r" % (lo, hi))
    if dy_cmp(dy(-3), dy(2)) >= 0 or dy_cmp(dy(1, -3), dy(1, -4)) <= 0 or dy_cmp(dy(-1, -3), dy(-1, -4)) >= 0 or dy_cmp(dy(0), dy(0)) != 0:
        raise SystemExit("gen_carlson_goldens selftest: dy_cmp")
    if inside(dy(-3, -3)) or not inside(dy(-1, -2)) or not inside(dy(0)):
        raise SystemExit("gen_carlson_goldens selftest: inside")
    if make_row("w0", "strict", 8, dy(-1), dy(1, -2)).split(" ")[-1] != "domain":
        raise SystemExit("gen_carlson_goldens selftest: W0 below -1/e")
    if make_row("wm1", "clip", 8, dy(-1, -1), dy(1)).split(" ")[-1] != "allreals":
        raise SystemExit("gen_carlson_goldens selftest: W-1 ball reaching 0 under Clip")
    r = make_row("w0", "clip", 8, dy(-1, -1), dy(1, -2)).split(" ")
    if r[9] != "ok" or r[10:16] != ["1", "1", "1", "1", "1", "1"]:
        raise SystemExit("gen_carlson_goldens selftest: W0 Clip lower end -1: %r" % r)
    if tight(dy(1), dy(1), 8) != dy(1, -6):
        raise SystemExit("gen_carlson_goldens selftest: TB of a point at 1")
    if venc(dy(-3, -3)) != "1 -1 3" or venc(dy(1, EXPONENT_MAX - 1)) != "0 %d 1" % EXPONENT_MAX:
        raise SystemExit("gen_carlson_goldens selftest: venc")
    if strip_skip_heavy(["--check", "D", "--skip-heavy"]) != ["--check", "D"] or strip_skip_heavy(["--selftest"]) != ["--selftest"]:
        raise SystemExit("gen_carlson_goldens selftest: --skip-heavy")
    print("gen_carlson_goldens selftest: ok")


def strip_skip_heavy(argv):
    """Drop --skip-heavy (documented no-op: no heavy tier; tools/goldens_regen.sh passes it in gate mode)."""
    return [a for a in argv if a != "--skip-heavy"]


def main(argv):
    goldlib.require_mpmath()
    selftest()
    argv = strip_skip_heavy(argv)
    if len(argv) == 2 and argv[0] == "--check":
        os.makedirs(argv[1], exist_ok=True)
        write_file(os.path.join(argv[1], GOLDEN_NAME))
        return 1 if goldlib.check_against(argv[1], GOLDEN_DIR, [GOLDEN_NAME]) else 0
    if argv == []:
        write_file(os.path.join(GOLDEN_DIR, GOLDEN_NAME))
        return 0
    if argv == ["--selftest"]:
        return 0
    raise SystemExit("usage: scripts/gen_carlson_goldens.py [--check DIR | --selftest] [--skip-heavy]")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
