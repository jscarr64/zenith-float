def draw_rad(rng, prec, mid):
    off = RAD_OFFSETS[rng.below(len(RAD_OFFSETS))]
    if off == "zero" or mid[2] == 0 and rng.below(2):
        return ZERO if off == "zero" else canon(0, 1, -prec)
    d = {"-p-1": -prec - 1, "-p": -prec, "-p+3": -prec + 3}.get(off)
    d = int(off) if d is None else d
    e = mid[1] + d
    kind = rng.below(3)
    m = 1 if kind == 0 else (3 if kind == 1 else 1 | (1 << 7) | rng.bits(7))
    return canon(0, m, e - m.bit_length())


def absmin(lo, hi):
    return Fraction(0) if lo <= 0 <= hi else min(abs(lo), abs(hi))


def image(op, n, am, ar, bm, br):
    alo, ahi = am - ar, am + ar
    if op == "abs":
        return (absmin(alo, ahi), max(abs(alo), abs(ahi)))
    if op == "mul_2exp":
        f = Fraction(2) ** n
        return alo * f, ahi * f
    if op == "neg":
        return -ahi, -alo
    if op in ("sqr", "powi"):
        if n == 0:
            return Fraction(1), Fraction(1)
        p, q = alo ** n, ahi ** n
        if n % 2 == 0 and alo < 0 < ahi:
            return Fraction(0), max(p, q)
        return min(p, q), max(p, q)
    if op == "sqrt":
        if ahi < 0:
            raise RowRejected("sqrt ball entirely negative")
        return max(alo, Fraction(0)), ahi
    if op == "inv":
        if alo <= 0 <= ahi:
            raise RowRejected("inv ball reaches 0")
        return 1 / ahi, 1 / alo
    blo, bhi = bm - br, bm + br
    if op == "hypot":   # the SQUARED image: truth() takes the root
        return absmin(alo, ahi) ** 2 + absmin(blo, bhi) ** 2, max(abs(alo), abs(ahi)) ** 2 + max(abs(blo), abs(bhi)) ** 2
    if op == "div":
        if blo <= 0 <= bhi:
            raise RowRejected("div divisor reaches 0")
        c = [x / y for x in (alo, ahi) for y in (blo, bhi)]
        return min(c), max(c)
    f = {"add": lambda x, y: x + y, "sub": lambda x, y: x - y, "mul": lambda x, y: x * y, "mul_exact": lambda x, y: x * y}[op]
    c = [f(x, y) for x in (alo, ahi) for y in (blo, bhi)]
    return min(c), max(c)


def at_mid(op, n, am, bm):
    return {"add": lambda: am + bm, "sub": lambda: am - bm, "mul": lambda: am * bm, "mul_exact": lambda: am * bm,
            "sqr": lambda: am ** n, "powi": lambda: am ** n, "neg": lambda: -am, "abs": lambda: abs(am),
            "mul_2exp": lambda: am * Fraction(2) ** n}[op]()


def truth(op, prec, n, am, ar, bm, br):
    w = 2 * prec + 64
    lo_x, hi_x = image(op, n, am, ar, bm, br)
    outward = False
    if op in INEXACT:
        # inward: both points lie in the true image, so a correct ball must contain them (outward points need not).
        root = op in ("sqrt", "hypot")

        def bound(x, up):
            return sqrt_bound(x, w, up) if root else x
        lo, hi = rnd(bound(lo_x, True), w, "Up"), rnd(bound(hi_x, False), w, "Down")
        if lo > hi:   # a point (or sub-ulp) image of an irrational value: outward pair; the result carries eps >> 2^-W there
            lo, hi = rnd(bound(lo_x, False), w, "Down"), rnd(bound(hi_x, True), w, "Up")
            outward = True
        fm = {"sqrt": lambda: sqrt_bound(max(am, Fraction(0)), w + 8, False), "div": lambda: am / bm, "inv": lambda: 1 / am,
              "hypot": lambda: sqrt_bound(am * am + bm * bm, w + 8, False)}[op]()
    else:
        lo, hi = lo_x, hi_x   # exact dyadic endpoints: an outward-rounded endpoint can lie outside a correct ball
        fm = at_mid(op, n, am, bm)
    big = max(abs(lo), abs(hi))
    u = ulp(fm, prec) if fm != 0 else (ulp(big, prec) if big != 0 else Fraction(0))
    spread = max(hi - fm, fm - lo)
    rref = rnd(spread + u, RREF_BITS, "Up") if spread + u != 0 else Fraction(0)
    return w, lo, hi, rref, outward


def cross_check(op, prec, n, w, am, ar, bm, br, lo, hi, outward=False, shift=0, row="selftest"):
    """mpmath.iv at W + 64 on the inputs scaled by 2^shift. HARD FAIL (Disagreement naming the row) unless the inner
    [LO, HI] * 2^shift lies inside the iv enclosure (an outward-fallback row: the enclosure inside [LO, HI]), and
    both endpoints are within 2 units at W."""
    from mpmath import iv, mp, mpf, ldexp
    iv.prec = w + 64
    mp.prec = w + 64

    def exact(x):
        v = from_fraction(x)
        man = v[2] if v[0] == 0 else -v[2]
        return ldexp(mpf((man, v[1] - v[2].bit_length())), shift) if v[2] else mpf(0)

    def ball(m, r):
        return iv.mpf([exact(m - r), exact(m + r)])
    a = ball(am, ar)
    if op == "sqrt":
        got = iv.sqrt(iv.mpf([exact(max(am - ar, Fraction(0))), exact(am + ar)]))
    elif op == "neg":
        got = -a
    elif op == "abs":
        lo_, hi_ = am - ar, am + ar
        got = iv.mpf([0, max(abs(a.a), abs(a.b))]) if lo_ < 0 < hi_ else (a if lo_ >= 0 else -a)
    elif op == "mul_2exp":
        got = iv.mpf([ldexp(a.a, n), ldexp(a.b, n)])
    elif op == "inv":
        got = 1 / a
    elif op == "div":
        got = a / ball(bm, br)
    elif op == "hypot":
        def sq(lo_, hi_, x):
            s = x ** 2
            return iv.mpf([0, s.b]) if lo_ < 0 < hi_ else s   # straddling square from 0, as for even powi
        got = iv.sqrt(sq(am - ar, am + ar, a) + sq(bm - br, bm + br, ball(bm, br)))
    elif op in ("sqr", "powi"):
        got = a ** n if n else iv.mpf(1)
        if n % 2 == 0 and n and am - ar < 0 < am + ar:
            got = iv.mpf([0, got.b])   # mpmath.iv's even power of a straddling interval may start below 0
    else:
        b = ball(bm, br)
        got = {"add": a + b, "sub": a - b, "mul": a * b, "mul_exact": a * b}[op]
    glo, ghi = mpf(got.a), mpf(got.b)
    mlo, mhi = exact(lo), exact(hi)
    tol = 2 * max(exact(ulp(lo, w)) if lo else mpf(0), exact(ulp(hi, w)) if hi else mpf(0))
    inside = (mlo <= glo and ghi <= mhi) if outward else (glo <= mlo and mhi <= ghi)
    if not inside or abs(glo - mlo) > tol or abs(ghi - mhi) > tol:
        raise Disagreement("row %s: %s p=%d n=%d shift=%d: %s [LO, HI] not %s the mpmath.iv enclosure at W+64 (or > 2 units at W): iv [%s, %s] vs ours [%s, %s]"
                           % (row, op, prec, n, shift, "outward" if outward else "inner", "around" if outward else "inside", glo, ghi, mlo, mhi))
    CHECKS[0] += 1


def shifted(v, s):
    return v if v[2] == 0 else (v[0], v[1] + s, v[2])


def in_range(v):
    return v[2] == 0 or EXPONENT_MIN <= v[1] <= EXPONENT_MAX


def make_row(op, prec, n, a, ar_v, b, br_v, shift=0, row="?", truth_at_scale0=False):
    """One row at scale 2^shift: computed exactly at scale 0, every value's exponent then shifted (all scale-invariant).
    mul_2exp edge rows pass n = 0 at scale 0 and the shift k; the written N is then k."""
    am, ar, bm, br = vfrac(a), vfrac(ar_v), vfrac(b), vfrac(br_v)
    if ar < 0 or br < 0:
        raise RowRejected("negative radius")
    w, lo, hi, rref, outward = truth(op, prec, n, am, ar, bm, br)
    if lo > hi:
        raise RowRejected("empty truth interval")
    cross_check(op, prec, n, w, am, ar, bm, br, lo, hi, outward, shift, row)
    vals = [shifted(v, 0 if truth_at_scale0 else shift) for v in (from_fraction(lo), from_fraction(hi), from_fraction(rref))]
    if shift and not truth_at_scale0 and not in_range(vals[2]):
        if ar != 0 or br != 0 or lo != hi:
            raise RowRejected("row %s: RREF below EXPONENT_MIN on a non-exact row" % row)
        vals[2] = ZERO   # exact ball, exact image: the only tight radius is 0
    if not all(in_range(v) for v in vals):
        raise RowRejected("row %s: LO/HI outside the exponent range" % row)
    # mul_2exp edge rows: the INPUT stays at scale 0 and N = k carries the shift; every other row shifts its inputs too.
    ins = (a, ar_v, b, br_v) if op == "mul_2exp" else tuple(shifted(v, shift) for v in (a, ar_v, b, br_v))
    nf = shift if op == "mul_2exp" and shift else n
    return goldlib.fmt_row(op, prec, w, nf, *[venc(v) for v in ins], *[venc(v) for v in vals])


def draw_row(op, prec, rng):
    """One row; mids span 2^-2000..2^2000 (cosmology 1e+-122 ~ 2^+-405 inside), radii from 0 to 8x the mid; signed mids."""
    a = draw_mid(rng, prec, op == "sqrt" and rng.below(4) != 0)
    if rng.below(8) == 0:
        a = ZERO
    ar = draw_rad(rng, prec, a)
    b, br, n = ZERO, ZERO, 0
    if op in ("add", "sub", "mul", "div", "hypot"):
        near = rng.below(3) == 0
        b = draw_mid(rng, prec, False, a[1] - 3, a[1] + 3) if near and a[2] else draw_mid(rng, prec, False)
        br = draw_rad(rng, prec, b)
    elif op == "mul_exact":
        b = draw_mid(rng, prec, False)
    elif op == "sqr":
        n = 2
    elif op == "powi":
        n = rng.below(10)
    elif op == "mul_2exp":
        n = rng.below(601) - 300
    return make_row(op, prec, n, a, ar, b, br)


def mid_class(a, k):
    """mpmath (not the crate) decides where m * 2^k lands: 'ovf' above EXPONENT_MAX, 'unf' below EXPONENT_MIN, else 'in'."""
    from mpmath import mpf, ldexp
    v = ldexp(mpf((a[2] if a[0] == 0 else -a[2], a[1] - a[2].bit_length())), k)
    e = int(v._mpf_[2]) + int(v._mpf_[3])   # 0.MANT * 2^EXP convention: EXP = exp + bitcount
    if e != a[1] + k:
        raise Disagreement("mpmath exponent %d != %d + %d" % (e, a[1], k))
    return "ovf" if e > EXPONENT_MAX else ("unf" if e < EXPONENT_MIN else "in")


def mul_2exp_edge_rows():
    """32 rows: PREC in EDGE_PRECS, sign +/-, mid in [1, 2) (EXP 1). MAX family (rad 2^-(p+1)): result EXP EMAX-1, EMAX,
    EMAX+1 (overflow) and k = i64::MAX (overflow). MIN family (exact, rad 0): result EXP EMIN+1, EMIN, EMIN-1 (underflow)
    and k = i64::MIN (underflow)."""
    out = []
    for prec in EDGE_PRECS:
        for sign in (0, 1):
            a = canon(sign, (1 << (prec - 1)) | 5, -(prec - 1))
            r = canon(0, 1, -prec - 1)
            # k = target EXP - EXP(a): the result's EXP is EMAX-1, EMAX, EMAX+1 and EMIN+1, EMIN, EMIN-1
            fam = [(EXPONENT_MAX + d - a[1], r) for d in (-1, 0, 1)] + [(I64_MAX, r)]
            fam += [(EXPONENT_MIN + d - a[1], ZERO) for d in (1, 0, -1)] + [(I64_MIN, ZERO)]
            for k, rad in fam:
                c = mid_class(a, k)
                if c == "in":
                    out.append(("mul_2exp", prec, 0, a, rad, ZERO, ZERO, k))
                else:
                    out.append(("mul_2exp_" + c, prec, k, a, rad))
    return out


def mul_2exp_unf_rad_rows():
    """2 rows, appended last: PREC in EDGE_PRECS, mid 0 (exact, so only the radius moves; signed zero has no row
    encoding), rad 2^-53, k = i64::MIN. 2^-53 * 2^i64::MIN is below the Mag exponent range, so the consumer pins the
    result radius at min_pos = finite(HALF_MANT, i64::MIN). A nonzero mid would underflow too and its rounding error
    would dominate the radius (that case is the mul_2exp_unf family)."""
    rad = canon(0, 1, -53)
    if rad[1] + I64_MIN >= I64_MIN:
        raise SystemExit("gen_arith_oracle: mul_2exp_unf_rad radius does not underflow the Mag range")
    return [("mul_2exp_unf_rad", prec, I64_MIN, ZERO, rad) for prec in EDGE_PRECS]


def hypot_edge_rows():
    """22 rows (11 per PREC in EDGE_PRECS): near EXPONENT_MAX (squares overflow; scale 2^(EMAX-2)) and EXPONENT_MIN
    (squares underflow; scale 2^(EMIN+400)), same and mixed signs; one side 0 (point and 0 +- r); mixed signs; |a| > 2^p |b|
    (gap p+10, exact b) and gap p+2 (b with radius); A straddling 0; both straddling 0."""
    out = []
    for prec in EDGE_PRECS:
        m1 = canon(0, (1 << (prec - 1)) | 5, -(prec - 1))
        m2 = canon(0, (1 << (prec - 1)) | 3, -prec)
        nm1 = (1, m1[1], m1[2])
        nm2 = (1, m2[1], m2[2])
        r = canon(0, 1, -prec - 1)
        far10, far2 = (0, m2[1] - prec - 10, m2[2]), (0, m2[1] - prec - 2, m2[2])
        big = canon(0, 1, 1)
        smax, smin = EXPONENT_MAX - 2, EXPONENT_MIN + 400
        out += [(m1, r, m2, r, smax), (nm1, r, m2, r, smax), (m1, r, m2, r, smin), (nm1, r, m2, r, smin),
                (m1, r, ZERO, ZERO, 0), (m1, r, ZERO, canon(0, 1, -3), 0), (nm1, r, m2, r, 0),
                (m1, r, far10, ZERO, 0), (m1, r, far2, (0, r[1] - prec - 2, r[2]), 0), (m2, big, m1, r, 0), (m2, big, nm2, big, 0)]
    return [("hypot", p_, 0) + row for p_, row in zip([p for p in EDGE_PRECS for _ in range(11)], out)]


def powi_fixed_rows():
    """36 rows: (1 + (37j+5) 2^-20)^n, n = 100 + 71j + i, PREC = POWI_FIXED_PRECS[i], j in 0..12 (slice_arith.rs
    powi_exact_input_within_one_ulp); exact input (rad 0); exact power LO = HI; RREF = U."""
    return [("powi", prec, 100 + 71 * j + i, from_fraction(1 + Fraction(37 * j + 5, 1 << 20)))
            for i, prec in enumerate(POWI_FIXED_PRECS) for j in range(12)]


def fixed_rows():
    """Every fixed row in order, as written lines (powi, mul_2exp edges, hypot edges)."""
    lines = []
    for op, prec, n, a in powi_fixed_rows():
        lines.append(make_row(op, prec, n, a, ZERO, ZERO, ZERO, row="powi-fixed %d" % len(lines)))
    for e in mul_2exp_edge_rows():
        if e[0] == "mul_2exp":
            op, prec, n, a, rad, b, br, k = e
            lines.append(make_row(op, prec, n, a, rad, b, br, shift=k, row="mul_2exp-edge k=%d" % k))
        else:
            op, prec, k, a, rad = e
            lines.append(goldlib.fmt_row(op, prec, 2 * prec + 64, k, venc(a), venc(rad), venc(ZERO), venc(ZERO),
                                         venc(ZERO), venc(ZERO), venc(ZERO)))
    for op, prec, n, a, ar, b, br, sh in hypot_edge_rows():
        lines.append(make_row(op, prec, n, a, ar, b, br, shift=sh, row="hypot-edge %d p=%d shift=%d" % (len(lines), prec, sh)))
    for op, prec, k, a, rad in mul_2exp_unf_rad_rows():
        # the normal truth + hard cross_check path (mpmath.iv at full scale 2^k); LO HI RREF are written at scale 0
        line = make_row("mul_2exp", prec, 0, a, rad, ZERO, ZERO, shift=k, row="mul_2exp_unf_rad p=%d" % prec,
                        truth_at_scale0=True)
        lines.append(op + line[len("mul_2exp"):])
    if len(lines) != FIXED_ROWS:
        raise SystemExit("gen_arith_oracle: %d fixed rows, want exactly %d" % (len(lines), FIXED_ROWS))
    return lines


def rows_per(prec):
    return 5 if prec <= 1024 else 2


def stream(path, precs):
    base = goldlib.stream_seed(200, 0)
    count = 0
    with open(path, "wb") as f:
        for line in HEADER:
            f.write((line + "\n").encode("ascii"))
        for oi, op in enumerate(OPS):
            for prec in precs:
                rng = Rng(goldlib.splitmix64(base ^ ((oi << 16) | prec)))
                got, tries = 0, 0
                while got < rows_per(prec):
                    tries += 1
                    if tries > 50 * rows_per(prec):
                        raise RowRejected("%s p=%d: too many redraws" % (op, prec))
                    try:
                        row = draw_row(op, prec, rng)
                    except RowRejected:
                        continue
                    f.write((row + "\n").encode("ascii"))
                    got += 1
                    count += 1
        want = len(OPS) * sum(rows_per(p) for p in precs)
        if count != want:
            raise SystemExit("gen_arith_oracle: %d random rows, want exactly %d" % (count, want))
        if tuple(precs) == PS:
            for row in fixed_rows():
                f.write((row + "\n").encode("ascii"))
                count += 1
            if count != WANT_ROWS:
                raise SystemExit("gen_arith_oracle: %d rows, want exactly %d" % (count, WANT_ROWS))
    print("rows %d, file bytes %d, peak RSS %d KiB (cap %d)" % (count, os.path.getsize(path), peak_rss(), RSS_CAP_KIB))


def rss_check(peak_kib):
    if peak_kib > RSS_CAP_KIB:
        raise SystemExit("gen_arith_oracle: peak RSS %d KiB over the %d KiB cap (rows must stream)" % (peak_kib, RSS_CAP_KIB))
    return peak_kib


def peak_rss():
    return rss_check(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)   # KiB on Linux


def selftest():
    def must_raise(exc, fn, what):
        try:
            fn()
        except exc:
            return
        raise SystemExit("gen_arith_oracle selftest: %s was not rejected" % what)
    one, half, two = canon(0, 1, 0), canon(0, 1, -1), canon(0, 1, 1)
    neg_one = canon(1, 1, 0)

    def lohi(op, n, a, ar, b=ZERO, br=ZERO):
        return truth(op, 8, n, vfrac(a), vfrac(ar), vfrac(b), vfrac(br))[1:]
    want = [
        (lohi("add", 0, one, half, one, half)[:2], (1, 3), "add [1+-1/2]+[1+-1/2]"),
        (lohi("mul_exact", 0, one, half, canon(1, 3, 0))[:2], (Fraction(-9, 2), Fraction(-3, 2)), "mul_exact [1+-1/2]*-3"),
        (lohi("sqr", 2, half, one)[:2], (0, Fraction(9, 4)), "sqr [1/2+-1] straddles 0"),
        (lohi("powi", 3, neg_one, half)[:2], (Fraction(-27, 8), Fraction(-1, 8)), "powi [-1+-1/2]^3"),
        (lohi("powi", 0, ZERO, two)[:3], (1, 1, Fraction(1, 128)), "powi n=0 is exactly 1, RREF = U = ulp(1) at 8 bits"),
        (lohi("sqrt", 0, one, one)[:2], (0, None), "sqrt [0,2] lo"),
        (lohi("neg", 0, one, half)[:2], (Fraction(-3, 2), Fraction(-1, 2)), "neg"),
        (lohi("sub", 0, one, ZERO, one, ZERO), (0, 0, 0), "1-1 exact zero, RREF 0"),
    ]
    for got, exp, what in want:
        if any(e is not None and g != e for g, e in zip(got, exp)):
            raise SystemExit("gen_arith_oracle selftest: %s: got %s want %s" % (what, got, exp))
    # RREF hand value: add exact mids 1+1 with radii 1/2: spread 1, U = ulp(2) at 8 bits = 2^-6
    if lohi("add", 0, one, half, one, half)[2] != 1 + Fraction(1, 64):
        raise SystemExit("gen_arith_oracle selftest: RREF hand value")
    must_raise(RowRejected, lambda: make_row("sqrt", 8, 0, canon(1, 3, 0), one, ZERO, ZERO), "an entirely negative sqrt ball")
    must_raise(Disagreement, lambda: cross_check("mul", 8, 0, 80, Fraction(1), Fraction(1, 2), Fraction(2), Fraction(1, 2), Fraction(1), Fraction(15, 4)), "a shrunk LO")
    must_raise(Disagreement, lambda: cross_check("powi", 8, 3, 80, Fraction(-1), Fraction(1, 2), Fraction(0), Fraction(0), Fraction(-27, 8), Fraction(-1, 4)), "a shrunk HI")
    want2 = [
        (lohi("div", 0, one, half, two, ZERO)[:2], (Fraction(1, 4), Fraction(3, 4)), "div [1+-1/2]/2"),
        (lohi("inv", 0, neg_one, half)[:2], (-2, Fraction(-2, 3)), "inv [-1+-1/2], HI inward"),
        (lohi("hypot", 0, canon(0, 3, 0), ZERO, canon(0, 1, 2), ZERO), (5, 5, Fraction(1, 32)), "hypot(3, 4) = 5 exactly, RREF = U"),
        (lohi("hypot", 0, ZERO, one, ZERO, one)[:1], (0,), "hypot of two balls around 0 starts at 0"),
    ]
    for got, exp, what in want2:
        if any(e is not None and g != e for g, e in zip(got, exp)):
            if what.startswith("inv") and got[0] == exp[0] and exp[1] - Fraction(1, 2 ** 79) <= got[1] <= exp[1]:
                continue   # -2/3 is not dyadic: HI is rounded DOWN (inward) to W = 80 bits
            raise SystemExit("gen_arith_oracle selftest: %s: got %s want %s" % (what, got, exp))
    must_raise(RowRejected, lambda: make_row("inv", 8, 0, one, one, ZERO, ZERO), "an inv ball reaching 0")
    must_raise(RowRejected, lambda: make_row("div", 8, 0, one, ZERO, one, two), "a div divisor reaching 0")
    must_raise(SystemExit, lambda: rss_check(RSS_CAP_KIB + 1), "a peak RSS over the cap")
    rss_check(RSS_CAP_KIB)
    # v3 (Spence/Paul): hard-fail containment. A correct inward row passes and counts exactly one check; a rounding slip
    # (LO nudged DOWN one ulp at W, outside the true image) must be rejected even though it is within the old 2-ulp tolerance.
    before = CHECKS[0]
    w8 = 2 * 8 + 64
    cross_check("add", 8, 0, w8, Fraction(1), Fraction(1, 2), Fraction(1), Fraction(1, 2), Fraction(1), Fraction(3))
    must_raise(Disagreement, lambda: cross_check("add", 8, 0, w8, Fraction(1), Fraction(1, 2), Fraction(1), Fraction(1, 2),
                                                 Fraction(1) - ulp(Fraction(1), w8), Fraction(3)), "LO slipped one ulp outward")
    must_raise(Disagreement, lambda: cross_check("add", 8, 0, w8, Fraction(1), Fraction(1, 2), Fraction(1), Fraction(1, 2),
                                                 Fraction(1), Fraction(3) + ulp(Fraction(3), w8)), "HI slipped one ulp outward")
    if CHECKS[0] - before != 1:
        raise SystemExit("gen_arith_oracle selftest: %d passing containment checks, want exactly 1" % (CHECKS[0] - before))
    want3 = [
        (lohi("abs", 0, neg_one, half)[:2], (Fraction(1, 2), Fraction(3, 2)), "abs [-1+-1/2]"),
        (lohi("abs", 0, half, one)[:2], (0, Fraction(3, 2)), "abs [1/2+-1] straddles 0"),
        (lohi("mul_2exp", -3, neg_one, half)[:2], (Fraction(-3, 16), Fraction(-1, 16)), "mul_2exp [-1+-1/2]*2^-3"),
    ]
    for got, exp, what in want3:
        if got != exp:
            raise SystemExit("gen_arith_oracle selftest: %s: got %s want %s" % (what, got, exp))
    # tools/goldens_regen.sh passes --skip-heavy to every slice generator in regen-gate mode (01af08d); S1 has no heavy rows, so it must parse
    if parse_args(["--check", "D", "--skip-heavy"]) != ("check", "D", None) or parse_args(["--check", "D"]) != ("check", "D", None):
        raise SystemExit("gen_arith_oracle selftest: --check DIR [--skip-heavy] not accepted")
    if parse_args(["--check", "D", "--bogus"]) is not None or parse_args(["--skip-heavy"]) is not None:
        raise SystemExit("gen_arith_oracle selftest: a bad argument list was accepted")
    print("gen_arith_oracle selftest: ok")


def parse_args(argv):
    """(mode, dir, n) or None. --skip-heavy is accepted after --check DIR (tools/goldens_regen.sh regen-gate mode); S1 has no heavy rows."""
    if len(argv) == 2 and argv[0] == "--check":
        return ("check", argv[1], None)
    if len(argv) == 3 and argv[0] == "--check" and argv[2] == "--skip-heavy":
        return ("check", argv[1], None)
    if len(argv) == 3 and argv[0] == "--sample":
        return ("sample", argv[1], int(argv[2]))
    if argv == []:
        return ("write", GOLDEN_DIR, None)
    if argv == ["--selftest"]:
        return ("selftest", None, None)
    return None


def main(argv):
    _guard()
    selftest()
    parsed = parse_args(argv)
    if parsed is None:
        raise SystemExit("usage: scripts/gen_arith_oracle.py [--check DIR [--skip-heavy] | --sample DIR N | --selftest]")
    mode, d, n = parsed
    if mode == "check":
        os.makedirs(d, exist_ok=True)
        stream(os.path.join(d, GOLDEN_NAME), PS)
        return 1 if goldlib.check_against(d, GOLDEN_DIR, [GOLDEN_NAME]) else 0
    if mode == "sample":
        os.makedirs(d, exist_ok=True)
        stream(os.path.join(d, GOLDEN_NAME), PS[:n])
        return 0
    if mode == "write":
        stream(os.path.join(d, GOLDEN_NAME), PS)
    return 0


