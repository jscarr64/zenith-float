def frac_me(x):
    """Fraction (dyadic) -> (man, exp) with x = man * 2^exp, man odd or 0."""
    if x == 0:
        return (0, 0)
    n, d = x.numerator, x.denominator
    if d & (d - 1):
        raise ValueError("not dyadic: %r" % x)
    e = -(d.bit_length() - 1)
    tz = (abs(n) & -abs(n)).bit_length() - 1
    return (n >> tz if n > 0 else -((-n) >> tz), e + tz)


def me_exp(man, exp):
    """zf/Arb exponent (0.m convention) of man * 2^exp, None for 0."""
    return None if man == 0 else exp + abs(man).bit_length()


def venc_me(man, exp):
    if man == 0:
        return "0 0 0"
    a = abs(man)
    tz = (a & -a).bit_length() - 1
    a >>= tz
    exp += tz
    return "%d %d %x" % (1 if man < 0 else 0, exp + a.bit_length(), a)


def in_zf(man, exp):
    e = me_exp(man, exp)
    return e is None or EMIN <= e <= EMAX


def to_arb_me(mid, rad):
    """(man, exp) mid and radius ((man, exp) or 'inf') -> exact arb (radius rounded up by FLINT's mag, as in to_arb)."""
    from flint import arb, fmpz, ctx
    with ctx.workprec(1 << 15):
        if rad == "inf":
            return arb(0, float("inf"))
        two = arb(2)
        m = arb(fmpz(mid[0])) * two ** fmpz(mid[1])
        if rad[0] == 0:
            return m
        return arb(m, arb(fmpz(rad[0])) * two ** fmpz(rad[1]))


def flint_parts_me(op, xs, ys, p):
    """xs, ys: two (mid, rad) per operand in (man, exp) form. Returns per part None (non-finite) or (mid, rad) as (man, exp)."""
    from flint import acb, ctx
    xa = acb(to_arb_me(*xs[0]), to_arb_me(*xs[1]))
    ya = acb(to_arb_me(*ys[0]), to_arb_me(*ys[1]))
    with ctx.workprec(p):
        z = xa * ya if op == "mul" else xa / ya
    out = []
    for part in (z.real, z.imag):
        if not part.is_finite():
            out.append(None)
            continue
        mm, me = part.mid().man_exp()
        if part.rad() == 0:
            rr = (0, 0)
        else:
            rm_, re_ = part.rad().mid().man_exp()
            rr = (int(rm_), int(re_))
        out.append(((int(mm), int(me)), rr))
    return out


def fmt_flint_me(f):
    if f is None:
        return "INF"
    (mm, me), (rm_, re_) = f
    if not (in_zf(mm, me) and in_zf(rm_, re_)):
        return "OUT"
    return venc_me(mm, me) + " " + venc_me(rm_, re_)


def fmt_true_shift(t, w, s):
    """Exact small-scale image t (or ALL) times 2^s, outward to w bits, clamped to zf's range as documented."""
    if t is ALLR:
        return "ALL"
    ends = []
    for v, up in ((t[0], False), (t[1], True)):
        r = round_out(v, w, up)
        man, exp = frac_me(r)
        e = me_exp(man, exp + s)
        if e is not None and e > EMAX:
            return "ALL"
        if e is not None and e < EMIN - SUB_BITS:
            if (r > 0) == up:  # outward end away from zero: the smallest normal magnitude
                ends.append("%d %d 1" % (0 if r > 0 else 1, EMIN))
            else:
                ends.append("0 0 0")
            continue
        ends.append(venc_me(man, exp + s))
    return " ".join(ends)


def shift_ball(b, s):
    mid, rad = b
    m = frac_me(mid)
    mm = (m[0], m[1] + s) if m[0] else (0, 0)
    if rad == "inf":
        return (mm, "inf")
    r = frac_me(rad)
    return (mm, (r[0], r[1] + s) if r[0] else (0, 0))


def fmt_in(b):
    (mid, rad) = b
    if not in_zf(*mid) or (rad != "inf" and not in_zf(*rad)):
        raise SystemExit("edge row input outside zf range: %r" % (b,))
    return venc_me(*mid) + " " + ("inf" if rad == "inf" else venc_me(*rad))


def edge_row(op, p, cls, x, y, sa=0, sb=0):
    """Uniform-shift row: x, y small Fraction balls, A = x * 2^sa, B = y * 2^sb."""
    xs = [shift_ball(b, sa) for b in x]
    ys = [shift_ball(b, sb) for b in y]
    xi = (interval(x[0]), interval(x[1]))
    yi = (interval(y[0]), interval(y[1]))
    tre, tim = true_mul(xi, yi) if op == "mul" else true_div(xi, yi, p)
    s = sa + sb if op == "mul" else sa - sb
    fl = flint_parts_me(op, xs, ys, p)
    w = 4 * p + 64
    f = [op, str(p), cls] + [fmt_in(b) for b in xs + ys]
    f += [fmt_true_shift(tre, w, s), fmt_true_shift(tim, w, s), fmt_flint_me(fl[0]), fmt_flint_me(fl[1])]
    return " ".join(f), fl


def pp_row(op, p, cls, xs, ys):
    """Per-part-shift row: xs, ys two ((man, exp), rad) each, rad (man, exp). T* = inner corner interval (see header)."""
    import functools
    from mpmath import iv, libmp
    w = 4 * p + 64
    iv.prec = 4 * w + 64
    def ends(b):
        (mm, me), rad = b
        m = iv.mpf(mm) * iv.mpf(2) ** me
        if rad[0] == 0:
            return [m]
        r = iv.mpf(rad[0]) * iv.mpf(2) ** rad[1]
        return [m - r, m + r]
    def lohi(v):
        return v._mpi_  # raw mpf (lower, upper)
    vals = ([], [])
    for a in ends(xs[0]):
        for b in ends(xs[1]):
            for c in ends(ys[0]):
                for d in ends(ys[1]):
                    if op == "mul":
                        re, im = a * c - b * d, a * d + b * c
                    else:
                        den = c * c + d * d
                        re, im = (a * c + b * d) / den, (b * c - a * d) / den
                    vals[0].append(lohi(re))
                    vals[1].append(lohi(im))
    def me_round(x, up):
        """mpf x to w bits toward +inf (up) or -inf, as (man, exp)."""
        sg, man, ex, _ = libmp.mpf_pos(x, w, "c" if up else "f")
        return ((-man if sg else man), ex) if man else (0, 0)
    tt = []
    for k in range(2):
        # inward: lo is an upper bound of the smallest corner value, hi a lower bound of the largest
        key = functools.cmp_to_key(libmp.mpf_cmp)
        lo = min((v[1] for v in vals[k]), key=key)
        hi = max((v[0] for v in vals[k]), key=key)
        lo_r, hi_r = me_round(lo, True), me_round(hi, False)
        if libmp.mpf_gt(libmp.from_man_exp(*lo_r), libmp.from_man_exp(*hi_r)):
            raise SystemExit("pp row %s: corner values not separated at W bits" % cls)
        tt.append(venc_me(*lo_r) + " " + venc_me(*hi_r))
    fl = flint_parts_me(op, xs, ys, p)
    f = [op, str(p), cls] + [fmt_in(b) for b in list(xs) + list(ys)]
    f += tt + [fmt_flint_me(fl[0]), fmt_flint_me(fl[1])]
    return " ".join(f), fl


def fb(v, rad=Fraction(0)):
    return (Fraction(v), rad if rad == "inf" else Fraction(rad))


def rel(v, k):
    """ball v +- |v| 2^-k (k may make a 1-bit radius)."""
    v = Fraction(v)
    return (v, abs(v) * pow2(-k))


def edge_cases():
    """(op, p, cls, kind, args): kind 'u' (x, y, sa, sb) or 'pp' (xs, ys)."""
    out = []
    a1 = (Fraction(3, 4), Fraction(-5, 8))          # exponents 0, 0
    a1r = (rel(Fraction(3, 4), 30), rel(Fraction(-5, 8), 30))
    b1 = (Fraction(11, 16), Fraction(9, 16))
    def X(t, k=None):
        return tuple((v, Fraction(0)) if k is None else rel(v, k) for v in t)
    for op in ("mul", "div"):
        for p in (53, 128):
            # EXPONENT_MAX (B3/B4): A at the top binade, B around 1 (fits / overflows by rounding or by a binade)
            for sb, tag in ((0, "b1"), (1, "b2"), (-1, "bhalf"), (-3, "beighth")):
                out.append((op, p, "emax_%s_exact" % tag, "u", (X(a1), X(b1), EMAX, sb)))
                out.append((op, p, "emax_%s_inexact" % tag, "u", (X(a1, 30), X(b1, 20), EMAX, sb)))
            # EXPONENT_MIN: A near the bottom (radii kept representable), B around 1 / below 1 / above 1
            for sa, tag in ((EMIN + p + 80, "lowrad"), (EMIN + 1, "bottom")):
                for sb in (0, 2, -2, -40):
                    out.append((op, p, "emin_%s_sb%d_exact" % (tag, sb), "u", (X(a1), X(b1), sa, sb)))
                    if tag == "lowrad":
                        out.append((op, p, "emin_%s_sb%d_inexact" % (tag, sb), "u", (X(a1, 30), X(b1, 20), sa, sb)))
            # cross: top binade with bottom binade
            # (an inexact operand at the bottom sits 40 binades up so its radius stays representable)
            lo = EMIN + 40
            out.append((op, p, "cross_max_min", "u", (X(a1, 30), X(b1, 20), EMAX - 1, lo)))
            out.append((op, p, "cross_min_max", "u", (X(a1, 30), X(b1, 20), lo, EMAX - 1)))
            out.append((op, p, "cross_max_max", "u", (X(a1, 30), X(b1, 20), EMAX - 1, EMAX - 1)))
            out.append((op, p, "cross_min_min", "u", (X(a1, 30), X(b1, 20), lo, lo)))
            out.append((op, p, "cross_max_min_exact", "u", (X(a1), X(b1), EMAX, EMIN + 1)))
            out.append((op, p, "cross_min_max_exact", "u", (X(a1), X(b1), EMIN + 1, EMAX)))
    # lagom edge (div): midpoint exponents L-1, L, L+1, L+2 (0.m convention) for A, then for B; and a lagom midpoint with a
    # non-lagom radius
    for p in (53, 128):
        for d in (-1, 0, 1, 2):
            out.append(("div", p, "lagom_a%+d" % d, "u", (X(a1, 30), X(b1, 25), LAGOM + d, 0)))
            out.append(("div", p, "lagom_an%+d" % d, "u", (X(a1, 30), X(b1, 25), -LAGOM - d, 0)))
            out.append(("div", p, "lagom_b%+d" % d, "u", (X(a1, 30), X(b1, 25), 0, LAGOM + d)))
            out.append(("div", p, "lagom_bn%+d" % d, "u", (X(a1, 30), X(b1, 25), 0, -LAGOM - d)))
            # axis divisors go straight to arb_div (lagom / non-lagom finite paths)
            out.append(("div", p, "lagom_axre_a%+d" % d, "u", (X(a1, 30), ((Fraction(11, 16), Fraction(11, 16) * pow2(-25)), (Fraction(0), Fraction(0))), LAGOM + d, 0)))
            out.append(("div", p, "lagom_axim_b%+d" % d, "u", (X(a1, 30), ((Fraction(0), Fraction(0)), (Fraction(9, 16), Fraction(9, 16) * pow2(-25))), 0, LAGOM + d)))
        out.append(("div", p, "lagom_mid_nonlagom_rad", "u", (X(a1, 40), ((Fraction(11, 16), Fraction(11, 16) * pow2(-40)), (Fraction(0), Fraction(0))), -LAGOM + 2, 0)))
    # arb_div accuracy at ARB_DIV_WIDE_ACC = 20: x and y with rel accuracy 19..22, lagom and non-lagom, axis divisor
    for p in (53, 128):
        for k in (20, 21, 22, 23):
            for sa, lt in ((0, "lagom"), (LAGOM + 1, "nonlagom")):
                ax = ((Fraction(11, 16), Fraction(1, 2) * pow2(-30)), (Fraction(0), Fraction(0)))
                out.append(("div", p, "acc_x_k%d_%s" % (k, lt), "u", ((rel(Fraction(3, 4), k), rel(Fraction(-5, 8), k)), ax, sa, 0)))
                ay = ((Fraction(11, 16), Fraction(1, 2) * pow2(-k)), (Fraction(0), Fraction(0)))
                out.append(("div", p, "acc_y_k%d_%s" % (k, lt), "u", (X(a1, 40), ay, sa, 0)))
    # acb_div's exact short-divisor branch: prec > 256 and both divisor mids within prec/2 bits
    for p in (256, 257, 258):
        for bits in (128, 129):
            m = (1 << (bits - 1)) | 1
            c = Fraction(m, 1 << bits)
            d = Fraction(-((1 << (bits - 1)) | 3), 1 << bits)
            out.append(("div", p, "fits_cd%d" % bits, "u", (X(a1, 20), ((c, Fraction(0)), (d, Fraction(0))), 0, 0)))
            out.append(("div", p, "fits_c%d_d3" % bits, "u", (X(a1, 20), ((c, Fraction(0)), (Fraction(3, 4), Fraction(0))), 0, 0)))
    # acb_inv hprec = max(prec + 3, 30) at p = 26 / 27 / 28
    for p in (25, 26, 27, 28):
        out.append(("div", p, "hprec_inexact", "u", (X(a1, 20), (rel(Fraction(11, 16), 22), rel(Fraction(9, 16), 22)), 0, 0)))
        cc = Fraction((1 << 27) + 5, 1 << 28)
        out.append(("div", p, "hprec_exact", "u", (X(a1), ((cc, Fraction(0)), (Fraction(-(1 << 26) - 3, 1 << 27), Fraction(0))), 0, 0)))
    # arb_div_wide reaches_zero: numerator rad == |mid|, just above, just below (radii with <= 30-bit mantissas), axis divisor
    # of low accuracy, both divisor signs
    for p in (53, 128):
        half = Fraction(1, 2)
        for rt, r in (("eq", half), ("up", half + pow2(-30)), ("dn", half - pow2(-31))):
            for sg in (1, -1):
                y = ((sg * Fraction(3, 4), Fraction(1, 8)), (Fraction(0), Fraction(0)))
                out.append(("div", p, "reach0_%s_y%s" % (rt, "p" if sg > 0 else "n"), "u", (((half, r), (-half, r)), y, 0, 0)))
                y2 = ((Fraction(0), Fraction(0)), (sg * Fraction(3, 4), Fraction(1, 8)))
                out.append(("div", p, "reach0_%s_iy%s" % (rt, "p" if sg > 0 else "n"), "u", (((half, r), (-half, r)), y2, 0, 0)))
    # per-part shifts (pp_): acb_inv's mag_add_lower with a squared lower bound below EXPONENT_MIN (re part 2^-(2^61) of im)
    for p in (53, 128):
        one = ((1, 0), (0, 0))
        zero = ((0, 0), (0, 0))
        for sre, tag in ((-(1 << 61), "re_tiny"), (-(1 << 61) - 5, "re_tinier"), (1 << 61, "re_huge")):
            c = ((3, sre - 2), (1, sre - 2 - 30))     # (3/4 +- 2^-30 * ...) * 2^sre
            d = ((-5, -3), (1, -3 - 30))
            out.append(("div", p, "pp_inv_%s" % tag, "pp", ((one, zero), (c, d))))
            out.append(("div", p, "pp_inv_%s_swap" % tag, "pp", ((one, zero), (d, c))))
    # exhaustive small precision: every p-bit mantissa (exponent 0), sign pattern and radius by index, three partners
    for p in range(2, 9):
        partners = [
            ("pe", ((Fraction(3, 4), Fraction(0)), (Fraction(-1, 2), Fraction(0)))),
            ("pi", (rel(Fraction(5, 8), 4), rel(Fraction(3, 8), 6))),
            ("pz", ((Fraction(1, 2), Fraction(1, 8)), (Fraction(0), Fraction(0)))),
        ]
        mants = list(range(1 << (p - 1), 1 << p))
        for i, m in enumerate(mants):
            m2 = mants[(i + 1) % len(mants)]
            sre = -1 if i & 1 else 1
            sim = -1 if i & 2 else 1
            v1 = sre * Fraction(m, 1 << p)
            v2 = sim * Fraction(m2, 1 << p)
            rk = i % 3
            def rr(v):
                return Fraction(0) if rk == 0 else (pow2(-p) if rk == 1 else abs(v) * Fraction(1, 4))
            x = ((v1, rr(v1)), (v2, rr(v2)))
            for pn, y in partners:
                for op in ("mul", "div"):
                    out.append((op, p, "exh_m%x_%s" % (m, pn), "u", (x, y, 0, 0)))
    return out


def edge_rows():
    out = []
    accs = set()
    for op, p, cls, kind, args in edge_cases():
        if kind == "u":
            row, _ = edge_row(op, p, cls, *args)
            if cls.startswith("acc_"):
                b = shift_ball(args[0][0] if cls.startswith("acc_x") else args[1][0], args[2] if cls.startswith("acc_x") else 0)
                accs.add((cls[:5], int(to_arb_me(*b).rel_accuracy_bits())))
        else:
            row, _ = pp_row(op, p, cls, *args)
        out.append(row)
    for need in (("acc_x", 20), ("acc_x", 21), ("acc_y", 20), ("acc_y", 21)):
        if need not in accs:
            raise SystemExit("edge rows: no %s row with FLINT rel_accuracy_bits %d (have %r)" % (need[0], need[1], sorted(accs)))
    return out


def write_edge(path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    rs = edge_rows()
    with open(path, "w", encoding="ascii", newline="\n") as fo:
        for h in EDGE_HEADER:
            fo.write(h + "\n")
        for r in rs:
            fo.write(r + "\n")
    print("edge rows %d, file bytes %d" % (len(rs), os.path.getsize(path)))



