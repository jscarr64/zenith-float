# ---- values ---------------------------------------------------------------------------------------------------------------
def pow2(e):
    return Fraction(1 << e) if e >= 0 else Fraction(1, 1 << -e)


def venc_frac(x):
    if x == 0:
        return "0 0 0"
    sign = 1 if x < 0 else 0
    a = abs(x)
    n, d = a.numerator, a.denominator
    if d & (d - 1):
        raise ValueError("not dyadic: %r" % x)
    t = -(d.bit_length() - 1)
    tz = (n & -n).bit_length() - 1
    n >>= tz
    t += tz
    return "%d %d %x" % (sign, t + n.bit_length(), n)


def floor_log2(a):
    e = a.numerator.bit_length() - a.denominator.bit_length()
    if pow2(e) > a:
        e -= 1
    return e


def round_out(x, w, up):
    """x rounded to w significant bits, toward +inf (up) or -inf."""
    if x == 0:
        return Fraction(0)
    e = floor_log2(abs(x))
    q = x / pow2(e + 1 - w)
    n = q.numerator // q.denominator
    if up and n != q:
        n += 1
    return n * pow2(e + 1 - w)


def round_mid(x, p):
    """x to p bits, nearest (generation only)."""
    if x == 0:
        return Fraction(0)
    e = floor_log2(abs(x))
    q = x / pow2(e + 1 - p)
    n = (2 * q.numerator + q.denominator) // (2 * q.denominator)
    return n * pow2(e + 1 - p)


# ---- draws ----------------------------------------------------------------------------------------------------------------
class Rng:
    def __init__(self, seed):
        self.g = goldlib.SplitMix64(seed)

    def below(self, n):
        return self.g.next() % n

    def bits(self, k):
        v = 0
        while k > 0:
            take = min(64, k)
            v = (v << take) | (self.g.next() >> (64 - take))
            k -= take
        return v


def rmid(rng, p, elo, ehi, sign=None):
    """random p-bit mid with exponent in [elo, ehi]."""
    m = rng.bits(p) | (1 << (p - 1))
    e = elo + rng.below(ehi - elo + 1)
    v = Fraction(m) * pow2(e - p)
    s = rng.below(2) if sign is None else sign
    return -v if s else v


def rrad(rng, mid, k):
    """4-bit-mantissa radius about |mid| * 2^-k (2^-k when mid is 0)."""
    m = 8 + rng.below(8)
    base = floor_log2(abs(mid)) if mid != 0 else 0
    return Fraction(m) * pow2(base - k - 3)


def ball(mid, rad):
    return (mid, rad)


# ---- exact images -----------------------------------------------------------------------------------------------------------
def interval(b):
    mid, rad = b
    if rad == "inf":
        return ALLR
    return (mid - rad, mid + rad)


def is_pt0(i):
    return i is not ALLR and i[0] == 0 and i[1] == 0


def contains0(i):
    return i is ALLR or (i[0] <= 0 <= i[1])


def prod(i, j):
    if is_pt0(i) or is_pt0(j):
        return (Fraction(0), Fraction(0))
    if i is ALLR or j is ALLR:
        return ALLR
    p = [i[0] * j[0], i[0] * j[1], i[1] * j[0], i[1] * j[1]]
    return (min(p), max(p))


def iadd(i, j):
    if i is ALLR or j is ALLR:
        return ALLR
    return (i[0] + j[0], i[1] + j[1])


def ineg(i):
    return ALLR if i is ALLR else (-i[1], -i[0])


def quot(i, j):
    if is_pt0(j):
        return ALLR
    if is_pt0(i):
        return (Fraction(0), Fraction(0))
    if i is ALLR or contains0(j):
        return ALLR
    q = [i[0] / j[0], i[0] / j[1], i[1] / j[0], i[1] / j[1]]
    return (min(q), max(q))


def true_mul(x, y):
    a, b = x
    c, d = y
    return iadd(prod(a, c), ineg(prod(b, d))), iadd(prod(a, d), prod(b, c))


def edge_re(iv, a, b, c0, c1, d0, d1):
    """(lo, hi) bounds of Re((a+ib)/(c+id)) over the y rectangle: corners exact, edge critical points as iv intervals."""
    lo, hi = None, None
    def take(vl, vu):
        nonlocal lo, hi
        lo = vl if lo is None else min(lo, vl)
        hi = vu if hi is None else max(hi, vu)
    for c in (c0, c1):
        for d in (d0, d1):
            v = (a * c + b * d) / (c * c + d * d)
            take(v, v)
    nx2 = a * a + b * b
    if nx2 == 0:
        return lo, hi
    def fiv(q):
        return iv.mpf(q.numerator) / iv.mpf(q.denominator)
    def ends(x):
        out = []
        for t in x._mpi_:
            sg, man, ex, _ = t
            if not man and ex:
                raise ValueError("non-finite iv endpoint")
            v = Fraction(int(man)) * pow2(int(ex))
            out.append(-v if sg else v)
        return out
    s = iv.sqrt(fiv(nx2))
    for fixed, e0, e1, vertical in ((c0, d0, d1, True), (c1, d0, d1, True), (d0, c0, c1, False), (d1, c0, c1, False)):
        if fixed == 0:
            continue
        p, q = (b, a) if vertical else (a, b)
        if p == 0:
            roots = [iv.mpf(0)] if q != 0 else []
        else:
            qf = q * fixed
            sg = 1 if qf >= 0 else -1
            r1 = (fiv(-qf) - sg * fiv(abs(fixed)) * s) / fiv(p)
            roots = [r1, fiv(-fixed * fixed) / r1]
        for r in roots:
            rl, rh = ends(r)
            if rh < e0 or rl > e1:
                continue
            f = fiv(fixed)
            val = (fiv(a) * f + fiv(b) * r) / (f * f + r * r) if vertical else (fiv(a) * r + fiv(b) * f) / (r * r + f * f)
            vl, vu = ends(val)
            take(vl, vu)
    return lo, hi


def rng_re_div(iv, aa, bb, cc, dd):
    lo, hi = None, None
    for a in aa:
        for b in bb:
            l, h = edge_re(iv, a, b, cc[0], cc[1], dd[0], dd[1])
            lo = l if lo is None else min(lo, l)
            hi = h if hi is None else max(hi, h)
    return (lo, hi)


def true_div(x, y, p):
    from mpmath import iv
    a, b = x
    c, d = y
    if is_pt0(c) and is_pt0(d):
        return ALLR, ALLR
    if is_pt0(a) and is_pt0(b):
        z = (Fraction(0), Fraction(0))
        return z, z
    if is_pt0(d):
        return quot(a, c), quot(b, c)
    if is_pt0(c):
        return quot(b, d), ineg(quot(a, d))
    if contains0(c) and contains0(d):
        return ALLR, ALLR
    if c is ALLR or d is ALLR or a is ALLR or b is ALLR:
        return ALLR, ALLR
    ends = [floor_log2(abs(v)) for i in (a, b, c, d) for v in i if v != 0]
    iv.prec = 8 * p + 512 + 4 * ((max(ends) - min(ends)) if ends else 0)
    re = rng_re_div(iv, a, b, c, d)
    im = rng_re_div(iv, b, (-a[1], -a[0]), c, d)
    return re, im


# ---- FLINT -------------------------------------------------------------------------------------------------------------------
def to_arb(b):
    from flint import arb, fmpz, ctx
    mid, rad = b
    with ctx.workprec(1 << 15):
        if rad == "inf":
            return arb(0, float("inf"))
        m = arb(fmpz(mid.numerator)) / arb(fmpz(mid.denominator))
        r = arb(fmpz(rad.numerator)) / arb(fmpz(rad.denominator))
        return arb(m, r)


def arb_frac(x):
    man, exp = x.man_exp()
    return Fraction(int(man)) * pow2(int(exp))


def flint_ref(op, x, y, p):
    from flint import acb, ctx
    xa = acb(to_arb(x[0]), to_arb(x[1]))
    ya = acb(to_arb(y[0]), to_arb(y[1]))
    with ctx.workprec(p):
        z = xa * ya if op == "mul" else xa / ya
    out = []
    for part in (z.real, z.imag):
        if not part.is_finite():
            out.append(None)
        else:
            out.append((arb_frac(part.mid()), arb_frac(part.rad().mid()) if part.rad() != 0 else Fraction(0)))
    return out


# ---- cases -------------------------------------------------------------------------------------------------------------------
Z = (Fraction(0), Fraction(0))
INFB = (Fraction(0), "inf")


def cases(op, p, rng):
    """(CLASS, A, B) for one op and prec, in a fixed order."""
    out = []
    def g(e=4, k=None, sign=None, elo=None):
        m = rmid(rng, p, (-e if elo is None else elo), e, sign)
        return (m, Fraction(0) if k is None else rrad(rng, m, k))
    ks = [8, 30] + ([p - 2] if p > 4 else [])
    # exact x exact, inexact x inexact (relative radius 2^-k), mixed
    for _ in range(2):
        out.append(("exact", (g(), g()), (g(), g())))
    for k in ks:
        out.append(("inexact_k%d" % min(k, 999), (g(k=k), g(k=k)), (g(k=k), g(k=k))))
    out.append(("mixed_radius", (g(), g(k=20)), (g(k=20), g())))
    # an exact-zero part in each position (Arb branch order), with exact and with inexact partners
    for pos in range(4):
        for k in (None, 12):
            parts = [g(k=k) for _ in range(4)]
            parts[pos] = Z
            out.append(("zero_part%d_%s" % (pos, "exact" if k is None else "inexact"), (parts[0], parts[1]), (parts[2], parts[3])))
    # zero mid with a radius in each position
    for pos in range(4):
        parts = [g(k=10) for _ in range(4)]
        parts[pos] = (Fraction(0), pow2(-6))
        out.append(("zero_mid_rad%d" % pos, (parts[0], parts[1]), (parts[2], parts[3])))
    # infinite radius in each position, then with an exact-zero partner part
    for pos in range(4):
        parts = [g(k=10) for _ in range(4)]
        parts[pos] = INFB
        out.append(("inf_rad%d" % pos, (parts[0], parts[1]), (parts[2], parts[3])))
        parts = [g() for _ in range(4)]
        parts[pos] = INFB
        parts[(pos + 2) % 4] = Z
        out.append(("inf_rad%d_zero%d" % (pos, (pos + 2) % 4), (parts[0], parts[1]), (parts[2], parts[3])))
    # mixed signs on all four parts
    for s in range(0, 16, 5):
        sg = [(s >> i) & 1 for i in range(4)]
        parts = [g(k=16, sign=sg[i]) for i in range(4)]
        out.append(("signs%x" % s, (parts[0], parts[1]), (parts[2], parts[3])))
    # huge and tiny exponents: re and im on different scales, both operands
    for e in ((1000, 100000) if op == "mul" else (1000, 4000)):
        out.append(("scale_e%d" % e, (g(e=e, elo=e - 2), g(e=-e + 2, elo=-e)), (g(e=-e + 2, elo=-e, k=9), g(e=e, elo=e - 2, k=9))))
        out.append(("tiny_e%d" % e, (g(e=-e + 2, elo=-e), g(e=-e + 2, elo=-e, k=5)), (g(e=-e + 2, elo=-e), g(e=-e + 2, elo=-e))))
    # near cancellation in ac - bd
    a = g(); b = g(); c = g()
    if a[0] != 0:
        dmid = round_mid(a[0] * c[0] / b[0], p)
        out.append(("cancel", (a, b), (c, (dmid, Fraction(0)))))
    if op == "div":
        # divisor rectangle containing 0, touching 0, exact zero, axis divisors reaching 0
        out.append(("div_box0", (g(k=10), g(k=10)), ((Fraction(1, 8), Fraction(1, 4)), (Fraction(-1, 8), Fraction(1, 4)))))
        out.append(("div_touch0", (g(), g()), ((Fraction(1), Fraction(1)), (Fraction(-1), Fraction(1)))))
        out.append(("div_exact0", (g(), g()), (Z, Z)))
        out.append(("div_axis_re0", (g(), Z), ((Fraction(1, 16), Fraction(1, 8)), Z)))
        out.append(("div_axis_im0", (Z, g()), (Z, (Fraction(1, 16), Fraction(1, 8)))))
        out.append(("div_axis_mix0", (g(), g()), (Z, (Fraction(-1, 16), Fraction(1, 8)))))
        # wide divisor and wide numerator (arb_div_wide), thin strip away from 0
        out.append(("div_wide_y", (g(k=40), g(k=40)), (g(k=3), g(k=3))))
        out.append(("div_wide_x", (g(k=2), g(k=2)), (g(k=40), g(k=40))))
        out.append(("div_strip", (g(), g()), ((Fraction(0), pow2(-64)), (pow2(-1000), Fraction(0)))))
        # exact divisor with few bits at high prec (acb_div's exact branch for prec > 256)
        out.append(("div_exact_short_y", (g(k=20), g(k=20)), ((Fraction(3), Fraction(0)), (Fraction(-5, 4), Fraction(0)))))
        out.append(("div_exact_short_y_exact_x", (g(), g()), ((Fraction(7, 2), Fraction(0)), (Fraction(9), Fraction(0)))))
    return out


def fmt_rad(r):
    return "inf" if r == "inf" else venc_frac(r)


def fmt_true(t, w):
    if t is ALLR:
        return "ALL"
    return venc_frac(round_out(t[0], w, False)) + " " + venc_frac(round_out(t[1], w, True))


def fmt_flint(f):
    if f is None:
        return "INF"
    return venc_frac(f[0]) + " " + venc_frac(f[1])


def rows():
    rng = Rng(goldlib.stream_seed(16, 2))
    out = []
    for op in ("mul", "div"):
        for p in PS:
            for cls, x, y in cases(op, p, rng):
                xi = (interval(x[0]), interval(x[1]))
                yi = (interval(y[0]), interval(y[1]))
                tre, tim = true_mul(xi, yi) if op == "mul" else true_div(xi, yi, p)
                fre, fim = flint_ref(op, x, y, p)
                w = 4 * p + 64
                f = [op, str(p), cls]
                for b in (x[0], x[1], y[0], y[1]):
                    f += [venc_frac(b[0]), fmt_rad(b[1])]
                f += [fmt_true(tre, w), fmt_true(tim, w), fmt_flint(fre), fmt_flint(fim)]
                out.append(" ".join(f))
    return out


# ---- R1 edge rows (Spence PR #40 R1): cball_arb_edge_rows.txt -------------------------------------------------------------
# Same row format as cball_arb_rows.txt, plus two tokens:
#   F* 'OUT': FLINT's part is finite but a midpoint or radius exponent lies outside zf's range [EMIN, EMAX] (zf cannot hold it;
#             the consumer checks containment only for that part).
#   Classes starting 'pp_' take a different exponent shift per part; their T* is not the whole image but the inner interval
#             [min, max] of the image values at the 16 corner pairs (the image of a rectangle is connected, so every point of
#             that interval is attained): mpmath iv at 4*W bits, rounded inward to W bits.
# Every other row: inputs are small dyadics times 2^SA (A) and 2^SB (B); the image is the exact small-scale image (as the main
# file) times 2^(SA+SB) (mul) or 2^(SA-SB) (div). An image end beyond EMAX makes the part 'ALL' (zf overflow is all reals,
# CONTRACT 10.4); an end more than SUB_BITS = 8192 binades below 2^EMIN is rounded
# outward to 0 or to +-2^(EMIN-1); ends nearer EMIN stay exact (zf subnormals).
EDGE_NAME = "cball_arb_edge_rows.txt"
EDGE_VERSION = 1
EMAX = (1 << 62) - 1
EMIN = -EMAX
LAGOM = (1 << 60) - 1
# zf holds values below 2^EMIN as subnormals (top bits at EMIN); image ends within this many binades below stay exact.
SUB_BITS = 8192

