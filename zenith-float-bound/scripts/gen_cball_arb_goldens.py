"""
Generates tests/goldens/slices/cball/cball_arb_rows.txt: FLINT (python-flint 0.9.0, FLINT 3.6.0) acb_mul / acb_div references and exact
true images for CBall::mul / CBall::div, the Arb port (CONTRACT 16.CB.4 / 16.CB.7). Run with ~/team-env/oracle-2026-10-30/bin/python under popslot:
    scripts/gen_cball_arb_goldens.py              write tests/goldens/slices/cball/cball_arb_rows.txt
    scripts/gen_cball_arb_goldens.py --check DIR  regenerate into DIR (never tests/goldens) and compare byte for byte
    scripts/gen_cball_arb_goldens.py --selftest   the generator's own checks
--skip-heavy may follow any of these and is a documented no-op (no heavy tier).

Each row gives the input rectangles A = [ARE +- ARER] x [AIM +- AIMR], B likewise, at PREC, and two references per output part:
  TRUE  the exact image of the rectangles (B minus {0} for div), rounded outward to W = 4*PREC + 64 bits: 'LO HI', or 'ALL' when the image is
        unbounded, nowhere defined, or (div with an unbounded divisor rectangle) not computed here; a consumer must contain [LO, HI], and give
        the whole line for ALL.
        mul: ac - bd and ad + bc have independent factors, so each part is an exact Minkowski interval sum of exact interval products.
        div: Re(x/y) is linear in x and harmonic in y away from 0, so its extrema over the rectangles are at an x corner and on a y edge:
        y corners exactly in Fraction, edge critical points (roots of p t^2 + 2 q f t - p f^2) with mpmath iv at 8*PREC + 512 + 4*S bits
        (S the binade spread of the nonzero input endpoints; a - |x| loses at most 2*S bits). Im(x/y) = Re((b - i a)/y). Axis divisors (re or im exactly 0) split exactly.
  FLINT acb_mul / acb_div at PREC on the same exact inputs (an infinite radius is the all-reals ball 0 +- inf, as zf stores it): 'MID RAD',
        or 'INF' for a non-finite part ([+/- inf], [nan +/- inf]). A consumer finite where FLINT is finite must have radius <= 2 * RAD.
A value is 'SIGN EXP MANT': (-1)^SIGN * MANT * 2^(EXP - bitlen(MANT)), MANT lowercase hex and odd, zero '0 0 0'. A radius is a value or 'inf'.
Row: OP PREC CLASS ARE ARER AIM AIMR BRE BRER BIM BIMR TRE TIM FRE FIM, each T* 'ALL' or two values, each F* 'INF' or two values.
"""
