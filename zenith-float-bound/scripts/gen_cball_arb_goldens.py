def selftest():
    # (1+2i)(3+4i) = -5 + 10i exactly; (1+2i)/(3+4i) = 11/25 + 2/25 i
    one = lambda v: (Fraction(v), Fraction(v))
    re, im = true_mul((one(1), one(2)), (one(3), one(4)))
    if re != (Fraction(-5), Fraction(-5)) or im != (Fraction(10), Fraction(10)):
        raise SystemExit("gen_cball_arb_goldens selftest: mul image")
    re, im = true_div((one(1), one(2)), (one(3), one(4)), 53)
    if not (re[0] <= Fraction(11, 25) <= re[1] and im[0] <= Fraction(2, 25) <= im[1]):
        raise SystemExit("gen_cball_arb_goldens selftest: div image")
    # x/(i d) with d reaching 0: Re is exactly 0 (axis split before the R1 test)
    re, im = true_div((one(2), one(0)), (one(0), (Fraction(-1), Fraction(1))), 53)
    if re != (Fraction(0), Fraction(0)) or im is not ALLR:
        raise SystemExit("gen_cball_arb_goldens selftest: axis 2/(i[-1,1])")
    re, im = true_div((one(0), one(2)), (one(0), (Fraction(-1), Fraction(1))), 53)
    if re is not ALLR or im != (Fraction(0), Fraction(0)):
        raise SystemExit("gen_cball_arb_goldens selftest: axis 2i/(i[-1,1]) im")
    # Re(1/(c + i)) over c in [-1, 1]: max 1/2 at c = 1 (corner), min -1/2 at c = -1; the edge d = 1 has critical points c = +-1
    re, _ = true_div((one(1), one(0)), ((Fraction(-1), Fraction(1)), one(1)), 53)
    if not (re[0] <= Fraction(-1, 2) and re[1] >= Fraction(1, 2) and re[1] - Fraction(1, 2) < Fraction(1, 10**30)):
        raise SystemExit("gen_cball_arb_goldens selftest: edge critical point")
    if venc_frac(Fraction(3, 4)) != "0 0 3" or venc_frac(Fraction(-8)) != "1 4 1":
        raise SystemExit("gen_cball_arb_goldens selftest: venc")
    if round_out(Fraction(1, 3), 4, True) != Fraction(11, 32) or round_out(Fraction(1, 3), 4, False) != Fraction(10, 32):
        raise SystemExit("gen_cball_arb_goldens selftest: round_out")
    if strip_skip_heavy(["--check", "D", "--skip-heavy"]) != ["--check", "D"]:
        raise SystemExit("gen_cball_arb_goldens selftest: --skip-heavy not stripped")
    # edge helpers: (man, exp) encoding and the zf-range clamp of a shifted image
    if frac_me(Fraction(-12)) != (-3, 2) or venc_me(-3, 2) != "1 4 3" or venc_me(12, 0) != "0 4 3":
        raise SystemExit("gen_cball_arb_goldens selftest: venc_me")
    if fmt_true_shift((Fraction(1, 2), Fraction(3, 4)), 8, EMAX) != "0 %d 1 0 %d 3" % (EMAX, EMAX):
        raise SystemExit("gen_cball_arb_goldens selftest: shift in range")
    if fmt_true_shift((Fraction(1, 2), Fraction(1)), 8, EMAX) != "ALL":
        raise SystemExit("gen_cball_arb_goldens selftest: shift past EMAX")
    if fmt_true_shift((Fraction(1, 2), Fraction(3, 4)), 8, EMIN - 1) != "0 %d 1 0 %d 3" % (EMIN - 1, EMIN - 1):
        raise SystemExit("gen_cball_arb_goldens selftest: subnormal shift stays exact")
    if fmt_true_shift((Fraction(1, 2), Fraction(3, 4)), 8, EMIN - SUB_BITS - 1) != "0 0 0 0 %d 1" % EMIN:
        raise SystemExit("gen_cball_arb_goldens selftest: shift below EMIN")
    if fmt_true_shift((Fraction(-3, 4), Fraction(-1, 2)), 8, EMIN - SUB_BITS - 1) != "1 %d 1 0 0 0" % EMIN:
        raise SystemExit("gen_cball_arb_goldens selftest: negative shift below EMIN")
    print("gen_cball_arb_goldens selftest: ok")


def strip_skip_heavy(argv):
    return [a for a in argv if a != "--skip-heavy"]


def main(argv):
    goldlib.require_mpmath()
    selftest()
    argv = strip_skip_heavy(argv)
    if len(argv) == 2 and argv[0] == "--check":
        os.makedirs(argv[1], exist_ok=True)
        write_file(os.path.join(argv[1], GOLDEN_NAME))
        write_edge(os.path.join(argv[1], EDGE_NAME))
        return 1 if goldlib.check_against(argv[1], GOLDEN_DIR, [GOLDEN_NAME, EDGE_NAME]) else 0
    if argv == []:
        write_file(os.path.join(GOLDEN_DIR, GOLDEN_NAME))
        write_edge(os.path.join(GOLDEN_DIR, EDGE_NAME))
        return 0
    if argv == ["--selftest"]:
        return 0
    raise SystemExit("usage: scripts/gen_cball_arb_goldens.py [--check DIR | --selftest] [--skip-heavy]")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
