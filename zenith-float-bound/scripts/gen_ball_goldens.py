class RowRejected(Exception):
    """A row the generator refuses to emit."""


class Disagreement(Exception):
    """mpmath and goldlib disagree on a row (a real finding)."""


# ---- values: (sign, exp, mant), mant odd or 0 ----------------------------------------------------------------------------------
def canon(sign, m, t):
    """The canonical value (-1)^sign * m * 2^t."""
    if m == 0:
        return (sign, 0, 0)
    tz = (m & -m).bit_length() - 1
    m >>= tz
    t += tz
    return (sign, t + m.bit_length(), m)


def vfrac(v):
    sign, exp, m = v
    if m == 0:
        return Fraction(0)
    t = exp - m.bit_length()
    f = Fraction(m << t) if t >= 0 else Fraction(m, 1 << -t)
    return -f if sign else f


def from_fraction(x, zero_sign=0):
    """The canonical value of a dyadic Fraction."""
    if x == 0:
        return (zero_sign, 0, 0)
    den = x.denominator
    if den & (den - 1):
        raise ValueError("not a dyadic rational: %s" % x)
    return canon(1 if x < 0 else 0, abs(x.numerator), -(den.bit_length() - 1))


def venc(v):
    return "%d %d %x" % (v[0], v[1], v[2])


def check_representable(v, iprec):
    """Reject an input whose mantissa has more than iprec bits (it is not exactly representable at its stated precision) or is not canonical."""
    sign, exp, m = v
    if sign not in (0, 1):
        raise RowRejected("bad sign %r" % (sign,))
    if m == 0:
        if exp != 0:
            raise RowRejected("zero with exponent %d" % exp)
        return
    if m & 1 == 0:
        raise RowRejected("even mantissa %x is not canonical" % m)
    if m.bit_length() > iprec:
        raise RowRejected("mantissa %x has %d bits, more than iprec %d" % (m, m.bit_length(), iprec))


# ---- the expected result ----------------------------------------------------------------------------------------------------
def isqrt_round_input(m, t, prec):
    """For sqrt(m * 2^t) with m > 0: (x, exact), x a Fraction that rounds like the true root at prec bits (the root itself when exact, else the midpoint of
    the two integer-scaled neighbours, which lies strictly inside one rounding cell because the integer root has at least prec + 4 bits)."""
    from math import isqrt
    if t % 2:
        m <<= 1
        t -= 1
    s = max(0, (2 * (prec + 4) - m.bit_length() + 1) // 2 + 1)
    n = m << (2 * s)
    t2 = t - 2 * s
    r = isqrt(n)
    scale = t2 // 2
    exact = (r * r == n)
    num = r if exact else 2 * r + 1
    den = 1 if exact else 2
    f = Fraction(num, den)
    return (f * (Fraction(2) ** scale if scale >= 0 else Fraction(1, 1 << -scale)), exact)


def zero_sign(op, mode, a, b):
    """The sign of an exact-zero result (documented convention, IEEE 754)."""
    if op in ("add", "sub"):
        sb = b[0] ^ (1 if op == "sub" else 0)
        if a[0] == sb:
            return a[0]
        return 1 if mode == "Down" else 0
    if op in ("mul", "div"):
        return a[0] ^ b[0]
    return a[0]       # sqrt(+-0)


def expected(op, prec, mode, a, b):
    """(R, inexact, is_zero_result) from exact Fractions and goldlib.round_fraction."""
    fa = vfrac(a)
    if op == "sqrt":
        if a[0] == 1 and a[2] != 0:
            raise RowRejected("sqrt of a negative nonzero value")
        if a[2] == 0:
            return ((a[0], 0, 0), False, True)
        x, exact = isqrt_round_input(a[2], a[1] - a[2].bit_length(), prec)
        v, inexact = goldlib.round_fraction(x, prec, mode)
        return (from_fraction(v), (not exact) or inexact, False)
    fb = vfrac(b)
    if op == "add":
        x = fa + fb
    elif op == "sub":
        x = fa - fb
    elif op == "mul":
        x = fa * fb
    elif op == "div":
        if fb == 0:
            raise RowRejected("zero divisor")
        x = fa / fb
    else:
        raise RowRejected("unknown op %r" % (op,))
    if x == 0:
        return ((zero_sign(op, mode, a, b), 0, 0), False, True)
    v, inexact = goldlib.round_fraction(x, prec, mode)
    return (from_fraction(v), inexact, False)


# ---- the mpmath cross-check -------------------------------------------------------------------------------------------------
def _mp():
    return goldlib.require_mpmath()


def to_mpf(v):
    from mpmath.libmp import from_man_exp, fzero
    sign, exp, m = v
    if m == 0:
        return fzero
    return from_man_exp(-m if sign else m, exp - m.bit_length())


def mpf_fraction(t):
    sign, man, exp, _bc = t
    f = Fraction(man) * (Fraction(2) ** exp if exp >= 0 else Fraction(1, 1 << -exp))
    return -f if sign else f


def mp_result(op, prec, mode_letter, a, b):
    from mpmath.libmp import mpf_add, mpf_sub, mpf_mul, mpf_div, mpf_sqrt
    ma = to_mpf(a)
    if op == "sqrt":
        return mpf_sqrt(ma, prec, mode_letter)
    mb = to_mpf(b)
    return {"add": mpf_add, "sub": mpf_sub, "mul": mpf_mul, "div": mpf_div}[op](ma, mb, prec, mode_letter)


def mp_exact_value(op, a, b):
    """The exact value as a Fraction for add, sub, mul, div (mpmath is not asked for exactness of sqrt)."""
    fa, fb = vfrac(a), vfrac(b) if b is not None else None
    return {"add": lambda: fa + fb, "sub": lambda: fa - fb, "mul": lambda: fa * fb, "div": lambda: fa / fb}[op]()


def check_flag(op, prec, mode, a, b, got, inexact):
    """The inexact flag: the rounded value differs from the exact one (sqrt: the square of the rounded value differs from the operand)."""
    flag = (got * got != vfrac(a)) if op == "sqrt" else (got != mp_exact_value(op, a, b))
    if flag != inexact:
        raise Disagreement("%s p=%d %s a=%s b=%s: inexact flag goldlib %s, mpmath-derived %s" % (op, prec, mode, venc(a), venc(b) if b else "-", inexact, flag))


def cross_check(op, prec, mode, a, b, r, inexact, is_zero_result):
    """Returns 'mpmath' (checked against mpmath), 'toodd' (checked through mpmath's neighbours), or 'goldlib' (zero result, convention only).
    Raises Disagreement on any difference."""
    _mp()
    if is_zero_result:
        return "goldlib"
    rv = vfrac(r)
    if mode in goldlib.MPMATH_MODE:
        got = mpf_fraction(mp_result(op, prec, goldlib.MPMATH_MODE[mode], a, b))
        if got != rv:
            raise Disagreement("%s p=%d %s a=%s b=%s: goldlib %s, mpmath %s" % (op, prec, mode, venc(a), venc(b) if b else "-", rv, got))
        check_flag(op, prec, mode, a, b, got, inexact)
        return "mpmath"
    # ToOdd through mpmath
    n = mpf_fraction(mp_result(op, prec, "n", a, b))
    d = mpf_fraction(mp_result(op, prec, "d", a, b))
    u = mpf_fraction(mp_result(op, prec, "u", a, b))
    if d == u:
        want = d
    else:
        d1 = mpf_fraction(mp_result(op, prec + 1, "d", a, b))
        u1 = mpf_fraction(mp_result(op, prec + 1, "u", a, b))
        if d1 == u1 and d1 not in (d, u):
            want = u if n == d else d        # a tie: nearest-even took one neighbour, ToOdd takes the other
        else:
            want = n
    if want != rv:
        raise Disagreement("%s p=%d ToOdd a=%s b=%s: goldlib %s, mpmath-derived %s" % (op, prec, venc(a), venc(b) if b else "-", rv, want))
    check_flag(op, prec, mode, a, b, want, inexact)
    return "toodd"


# ---- operand generation -----------------------------------------------------------------------------------------------------
class Rng:
    def __init__(self, seed):
        self.g = goldlib.SplitMix64(seed)

    def below(self, n):
        return (self.g.next() * n) >> 64

    def bits(self, k):
        acc = 0
        got = 0
        while got < k:
            acc = (acc << 64) | self.g.next()
            got += 64
        return acc & ((1 << k) - 1)


def pattern(idx, bits, rng):
    """A mantissa with exactly `bits` bits (top bit set); 9 patterns (the Rust set also has tie patterns, which are structured rows here)."""
    top = 1 << (bits - 1)
    full = (1 << bits) - 1
    if idx == 0:
        return top
    if idx == 1:
        return top | 1
    if idx == 2:
        return full
    if idx == 3:
        return full - 1 if bits >= 2 else full
    if idx == 4:
        return top | (top >> 1)
    if idx == 5:      # 1010...1011 style: alternating from the top, low bit set
        m = 0
        for i in range(0, bits, 2):
            m |= 1 << (bits - 1 - i)
        return m | 1
    if idx == 6:      # 0101... pattern with the top bit forced
        m = 0
        for i in range(1, bits, 2):
            m |= 1 << (bits - 1 - i)
        return m | top
    if idx == 7:      # a single bit below the top
        return top | (1 << rng.below(bits - 1)) if bits >= 2 else top
    return top | rng.bits(bits)           # uniform with the top bit forced


def draw_exp(rng, prec, anchor):
    """One exponent: 30% edge (within 3 of +-EXP_LIMIT), 20% near 0 (+-64), 30% uniform, 10% 2^k +-1, 10% anchor + gap (near 0 without an anchor)."""
    r = rng.below(100)
    if r < 30:
        k = rng.below(4)
        return (EXP_LIMIT - k) if rng.below(2) else (-EXP_LIMIT + k)
    if r < 50:
        return rng.below(129) - 64
    if r < 80:
        return rng.below(2 * EXP_LIMIT + 1) - EXP_LIMIT
    if r < 90:
        k = rng.below(15)
        neg = rng.below(2)
        d = rng.below(3) - 1
        return max(-EXP_LIMIT, min(EXP_LIMIT, (-(1 << k) if neg else (1 << k)) + d))
    gaps = (0, 1, 2, prec - 1, prec, prec + 1, prec + GUARD - 1, prec + GUARD, prec + GUARD + 1, 1 + rng.below(2 * EXP_LIMIT))
    gap = gaps[rng.below(10)]
    sign = -1 if rng.below(2) else 1
    if anchor is None:
        return max(-64, min(64, sign * gap))
    return max(-EXP_LIMIT, min(EXP_LIMIT, anchor + sign * gap))


def pick_iprec(rng, prec):
    c = rng.below(5)
    if c < 2:
        return prec
    if c == 2:
        return prec + 1 if (prec + 1 <= 64 or prec > 64) else 64
    if c == 3:
        return max(1, prec - 1)
    return 64 if prec <= 64 else prec


def draw_operand(rng, prec, iprec, anchor, allow_zero=True, allow_neg=True):
    sign = rng.below(2) if allow_neg else 0
    zsel = rng.below(20)
    bsel = rng.below(5)
    pidx = rng.below(9)
    bits = iprec if bsel < 3 else 1 + rng.below(iprec)
    m = pattern(pidx, bits, rng)
    e = draw_exp(rng, prec, anchor)
    if allow_zero and zsel == 0:
        return (sign, 0, 0)
    return canon(sign, m, e - bits)


def structured(op, prec, rng):
    """The structured operand sets of one (op, prec): list of (iprec, a, b). Same draws for every mode."""
    out = []
    p = prec
    ip_p = p if p != 64 else 64
    ip_p1 = min(p + 1, 64) if p <= 64 else p + 1

    def E():
        return draw_exp(rng, p, None)

    def full(bits, idx=2):
        return pattern(idx, bits, rng)

    def val(sign, m, bits, e):
        return canon(sign, m, e - bits)

    zero = [(0, 0, 0), (1, 0, 0)]
    x = lambda sign, e, idx=2: val(sign, full(ip_p, idx), ip_p, e)
    if op in ("add", "sub"):
        for za in zero:
            for zb in zero:
                out.append((1, za, zb))
        for s in (0, 1):
            out.append((ip_p, zero[s], x(0, E())))
            out.append((ip_p, x(1, E()), zero[s]))
        for idx in (2, 5, 8):                     # exact cancellation: x - x and x + (-x)
            e = E()
            a = x(0, e, idx)
            out.append((ip_p, a, (1, a[1], a[2])))
            out.append((ip_p, a, a))
        e = E()                                   # near cancellation: one unit apart, and a binade just below
        a = val(0, (1 << p) - 1, p, e)
        out.append((ip_p, a, val(1, (1 << p) - 2 if p >= 2 else 1, p, e)))
        out.append((ip_p, a, val(0, (1 << p) - 2 if p >= 2 else 1, p, e)))
        out.append((ip_p, val(0, 1 << (p - 1), p, e), val(1, (1 << p) - 1, p, e - 1)))
        out.append((ip_p, val(0, 1 << (p - 1), p, e), val(0, (1 << p) - 1, p, e - 1)))
        for sg in ((0, 0), (1, 1), (0, 1)):       # carries
            e = E()
            out.append((ip_p, val(sg[0], (1 << p) - 1, p, e), val(sg[1], (1 << p) - 1, p, e)))
            out.append((ip_p, val(sg[0], (1 << p) - 1, p, e), val(sg[1], 1, p, e - p + 1)))
        # exact ties at p, and one tick either side
        e = E()
        a = val(0, full(p, 5) if p >= 2 else 1, p, e)
        half = canon(0, 1, e - p - 1)
        out.append((ip_p, a, half))
        out.append((ip_p, (1, a[1], a[2]), (1, half[1], half[2])))
        out.append((ip_p, a, (1, half[1], half[2])))
        if p >= 2:
            k = min(p - 1, 10)
            out.append((ip_p, a, canon(0, (1 << k) + 1, e - p - 1 - k)))
            out.append((ip_p, a, canon(0, (1 << k) - 1, e - p - 1 - k)))
        out.append((ip_p, val(0, 1 << (p - 1), p, e), canon(1, 1, e - p - 2)))     # tie just below a power of two
        # huge gaps (the controlled-gap classes)
        seen = []
        for g in (0, 1, 2, p - 1, p, p + 1, p + GUARD - 1, p + GUARD, p + GUARD + 1, 1500, 20000):
            if g < 0 or g in seen:
                continue
            seen.append(g)
            e = E()
            e = max(-EXP_LIMIT + g, min(EXP_LIMIT, e))
            sg = (len(seen) % 2, (len(seen) // 2) % 2)
            out.append((ip_p, val(sg[0], full(ip_p, 8), ip_p, e), val(sg[1], full(ip_p, 2), ip_p, e - g)))
        if p == 3:                                # 81/64 = 1 + 17/64 = 2 - 47/64 at p = 3, directed rows
            if op == "add":
                out.append((5, canon(0, 1, 1), canon(0, 17, -6)))
            else:
                out.append((6, canon(0, 2, 0), canon(0, 47, -6)))
    elif op == "mul":
        for za in zero:
            for zb in zero:
                out.append((1, za, zb))
        for s in (0, 1):
            out.append((ip_p, zero[s], x(0, E())))
            out.append((ip_p, x(1, E()), zero[s]))
        out.append((ip_p, val(0, 1 << (p - 1), p, E()), x(0, E(), 8)))
        out.append((ip_p, val(1, 1 << (p - 1), p, E()), x(1, E(), 8)))
        e1, e2 = E(), E()
        a = x(0, e1)
        out.append((ip_p, a, a))
        out.append((ip_p, x(0, e1, 5), x(1, e2, 5)))
        out.append((ip_p, x(0, e1), x(0, e2, 1)))
        if p >= 3:                                # (2^k + 1)(2^j + 1), k + j = p, k < j: an exact product tie at p
            k = max(1, (p - 1) // 2)
            j = p - k
            for sg in ((0, 0), (1, 0), (1, 1)):
                out.append((p, canon(sg[0], (1 << k) + 1, E()), canon(sg[1], (1 << j) + 1, E())))
        if p == 3:                                # 9/8 * 9/8 = 81/64
            out.append((4, canon(0, 9, -3), canon(0, 9, -3)))
            out.append((4, canon(1, 9, -3), canon(0, 9, -3)))
    elif op == "div":
        for za in zero:
            for zb in ((0, 1, 1), (1, 1, 1)):
                out.append((1, za, zb))
        e1, e2 = E(), E()
        out.append((ip_p, val(0, 1 << (p - 1), p, e1), val(0, 1 << (p - 1), p, e2)))            # power of two over power of two: exact
        out.append((ip_p, x(0, e1), val(1, 1 << (p - 1), p, e2)))                               # exact: divisor is a power of two
        out.append((ip_p, val(0, 1 << (p - 1), p, e1), canon(0, 3, e2)))                          # 1/3 style: never exact
        out.append((ip_p, x(0, e1), x(0, e2)))                                                  # equal mantissas: exactly a power of two
        out.append((ip_p, x(0, e1, 5), x(1, e2, 8)))
        out.append((ip_p, x(1, e1, 8), x(1, e2, 5)))
        out.append((ip_p, x(0, e1, 0), x(0, e2, 1)))
        out.append((ip_p, x(0, e1, 1), x(0, e2, 0)))
        out.append((ip_p, x(0, e1, 3), x(0, e2, 4)))                                            # mantissa ratio below and above 1
        out.append((ip_p, x(0, e1, 4), x(0, e2, 3)))
        if p == 3:                                # 81/64 as 81 / 64
            out.append((7, canon(0, 81, 0), canon(0, 1, 6)))
            out.append((7, canon(1, 81, 0), canon(0, 1, 6)))
    else:             # sqrt
        out.append((1, zero[0], None))
        out.append((1, zero[1], None))
        for idx in (0, 1, 2, 5, 8):
            for par in (0, 1):
                e = 2 * (E() // 2) + par
                out.append((ip_p, x(0, e, idx), None))
        r = 3 if p < 3 else (1 << (p // 2)) + 1                                     # a perfect square with a short root
        out.append((2 * r.bit_length(), canon(0, r * r, E() // 2 * 2), None))
        out.append((2 * r.bit_length(), canon(0, r * r, E() // 2 * 2 + 1), None))
        r = (1 << p) + 1                                                            # (2^p + 1)^2: the root is an exact tie at p
        out.append((2 * r.bit_length(), canon(0, r * r, E() // 2 * 2), None))
        out.append((2 * r.bit_length(), canon(0, r * r, E() // 2 * 2 + 1), None))
        if p == 3:
            out.append((7, canon(0, 81, -6), None))                              # sqrt(81/64) = 9/8, a tie at p = 3
    return out


def random_sets(op, prec, rng, count):
    out = []
    for _ in range(count):
        ip = pick_iprec(rng, prec)
        if op == "sqrt":
            out.append((ip, draw_operand(rng, prec, ip, None, allow_zero=False, allow_neg=False), None))
            continue
        a = draw_operand(rng, prec, ip, None)
        b = draw_operand(rng, prec, ip, None if a[2] == 0 else a[1], allow_zero=(op != "div"))
        out.append((ip, a, b))
    return out


# ---- rows -------------------------------------------------------------------------------------------------------------------
def make_row(op, prec, mode, iprec, a, b, stats):
    check_representable(a, iprec)
    if b is not None:
        check_representable(b, iprec)
    r, inexact, is_zero = expected(op, prec, mode, a, b)
    how = cross_check(op, prec, mode, a, b, r, inexact, is_zero)
    stats[how] = stats.get(how, 0) + 1
    fields = [op, str(prec), mode, str(iprec), venc(a)]
    if b is not None:
        fields.append(venc(b))
    fields.append(venc(r))
    fields.append("1" if inexact else "0")
    return " ".join(fields)


def row_key(row):
    f = row.split(" ")
    return (OPS.index(f[0]), int(f[1]), MODES.index(f[2]), row)


def build_rows():
    """All rows (sorted, de-duplicated) and the statistics."""
    base = goldlib.stream_seed(2, 0)
    stats = {}
    rows = set()
    for oi, op in enumerate(OPS):
        for prec in PS_FAST:
            rng = Rng(goldlib.splitmix64(base ^ ((oi << 32) | prec)))
            sets = [(max(ip, a[2].bit_length(), b[2].bit_length() if b else 0), a, b) for ip, a, b in structured(op, prec, rng)]
            sets += random_sets(op, prec, rng, ROWS_RANDOM)
            for iprec, a, b in sets:
                for mode in MODES:
                    rows.add(make_row(op, prec, mode, iprec, a, b, stats))
    return sorted(rows, key=row_key), stats


def write_file(path):
    rows, stats = build_rows()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    goldlib.write_lines(path, HEADER + rows)
    per_op = {}
    for r in rows:
        per_op[r.split(" ")[0]] = per_op.get(r.split(" ")[0], 0) + 1
    print("rows %d (%s)" % (len(rows), ", ".join("%s %d" % (op, per_op.get(op, 0)) for op in OPS)))
    print("cross-checks: mpmath %d, toodd-via-mpmath %d, goldlib-only (exact zero results) %d" % (stats.get("mpmath", 0), stats.get("toodd", 0), stats.get("goldlib", 0)))
    print("file bytes %d" % os.path.getsize(path))


# ---- self-test: the generator's own negative tests --------------------------------------------------------------------------
def selftest():
    def must_raise(exc, fn, what):
        try:
            fn()
        except exc:
            return
        raise SystemExit("gen_ball_goldens selftest: %s was not rejected" % what)

    # an input with more mantissa bits than IPREC, an even mantissa, a zero with an exponent
    must_raise(RowRejected, lambda: make_row("add", 3, "Up", 3, canon(0, 0b1001, 0), canon(0, 1, 0), {}), "a 4-bit input at iprec 3")
    must_raise(RowRejected, lambda: check_representable((0, 5, 4), 8), "an even mantissa")
    must_raise(RowRejected, lambda: check_representable((0, 3, 0), 8), "a zero with an exponent")
    must_raise(RowRejected, lambda: make_row("div", 3, "Up", 3, canon(0, 1, 0), (0, 0, 0), {}), "a zero divisor")
    must_raise(RowRejected, lambda: make_row("sqrt", 3, "Up", 3, canon(1, 1, 0), None, {}), "sqrt of a negative")
    # a perturbed expected value is reported as a disagreement, for a mpmath mode and for ToOdd
    a, b = canon(0, 5, 0), canon(0, 3, -4)
    for mode in ("Up", "ToEven", "ToOdd"):
        r, inexact, z = expected("add", 3, mode, a, b)
        good = cross_check("add", 3, mode, a, b, r, inexact, z)
        bad_r = (r[0], r[1] + 1, r[2])
        must_raise(Disagreement, lambda: cross_check("add", 3, mode, a, b, bad_r, inexact, z), "a perturbed %s result" % mode)
        must_raise(Disagreement, lambda: cross_check("add", 3, mode, a, b, r, not inexact, z), "a flipped inexact flag (%s)" % mode)
        assert good in ("mpmath", "toodd")
    # hand-derived values: 81/64 at p = 3 (mul of 9/8 by 9/8): nearest 5/4, Up 3/2, Down 5/4
    a = canon(0, 9, -3)
    want = {"ToEven": (0, 1, 5), "ToOdd": (0, 1, 5), "Up": (0, 1, 3), "Down": (0, 1, 5), "ToZero": (0, 1, 5), "FromZero": (0, 1, 3)}
    for mode, v in want.items():
        r, inexact, _ = expected("mul", 3, mode, a, a)
        if r != v or not inexact:
            raise SystemExit("gen_ball_goldens selftest: 9/8*9/8 at p=3 %s gave %s" % (mode, r))
    # a tie at p = 1: 2 + 1 = 3 lies between 2 and 4; the unit count of 2 is odd, so ToEven takes 4 and ToOdd takes 2
    t1 = expected("add", 1, "ToEven", canon(0, 1, 1), canon(0, 1, 0))[0]
    t2 = expected("add", 1, "ToOdd", canon(0, 1, 1), canon(0, 1, 0))[0]
    if t1 != canon(0, 1, 2) or t2 != canon(0, 1, 1):
        raise SystemExit("gen_ball_goldens selftest: tie rows at p=1 gave %s %s" % (t1, t2))
    # zero-sign convention
    if expected("add", 3, "Down", canon(0, 5, 0), canon(1, 5, 0))[0] != (1, 0, 0) or expected("add", 3, "Up", canon(0, 5, 0), canon(1, 5, 0))[0] != (0, 0, 0):
        raise SystemExit("gen_ball_goldens selftest: exact cancellation sign")
    if expected("mul", 3, "Up", (1, 0, 0), canon(0, 3, 0))[0] != (1, 0, 0):
        raise SystemExit("gen_ball_goldens selftest: -0 * x")
    # sqrt: an exact root is exact, an inexact one is flagged, and the sticky midpoint agrees with mpmath for every mode
    for m, e in ((1, 2), (1, 3), (9, 4), (81, -6), (7, 1), (5, -9), (3, 40)):
        for mode in MODES:
            r, inexact, z = expected("sqrt", 5, mode, canon(0, m, e - m.bit_length()), None)
            cross_check("sqrt", 5, mode, canon(0, m, e - m.bit_length()), None, r, inexact, z)
    r, inexact, _ = expected("sqrt", 5, "Up", canon(0, 81, -6), None)
    if inexact or r != canon(0, 9, -3):
        raise SystemExit("gen_ball_goldens selftest: sqrt(81/64) at p=5 must be exactly 9/8")
    print("gen_ball_goldens selftest: ok")


def main(argv):
    goldlib.require_mpmath()
    selftest()
    if len(argv) == 2 and argv[0] == "--check":
        os.makedirs(argv[1], exist_ok=True)
        write_file(os.path.join(argv[1], GOLDEN_NAME))
        return 1 if goldlib.check_against(argv[1], GOLDEN_DIR, [GOLDEN_NAME]) else 0
    if argv == []:
        write_file(os.path.join(GOLDEN_DIR, GOLDEN_NAME))
        return 0
    if argv == ["--selftest"]:
        return 0
    raise SystemExit("usage: ~/team-env/oracle-2026-10-30/bin/python scripts/gen_ball_goldens.py [--check DIR | --selftest]")


