fn rm_of(name: &str) -> Option<RoundingMode> {
    match name {
        "ToEven" => Some(RoundingMode::ToEven),
        "Up" => Some(RoundingMode::Up),
        "None" => Some(RoundingMode::None),
        _ => None,
    }
}

#[test]
fn sin_of_huge_power_of_two_is_correctly_rounded() -> Result<(), String> {
    let mut cc = Consts::new().map_err(|e| format!("{e:?}"))?;
    let mut bad = Vec::new();
    for &(k, p, name, bits) in REF {
        let rm = rm_of(name).ok_or_else(|| format!("bad rm {name}"))?;
        let x = ExactNum::pow2(k, 64).map_err(|e| format!("{e:?}"))?;
        let want = ExactNum::parse(bits, Radix::Bin, 512, RoundingMode::None, &mut cc);
        let got = x.sin(p, rm, &mut cc);
        if got != want {
            bad.push(format!("k={k} p={p} {name}: got {got:?}, want {bits}"));
        }
    }
    if bad.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "{} of {} rows differ:\n{}",
            bad.len(),
            REF.len(),
            bad.join("\n")
        ))
    }
}
