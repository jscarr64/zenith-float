fn rm_of(name: &str) -> Option<RoundingMode> {
    match name {
        "ToEven" => Some(RoundingMode::ToEven),
        "Up" => Some(RoundingMode::Up),
        "None" => Some(RoundingMode::None),
        _ => None,
    }
}

#[test]
fn rem_pi_is_target_independent() -> Result<(), String> {
    let mut cc = Consts::new().map_err(|e| format!("{e:?}"))?;
    let ten = ExactNum::from(10);
    let mut bad = Vec::new();
    for &(p, name, bits) in REF {
        let rm = rm_of(name).ok_or_else(|| format!("bad rm {name}"))?;
        let want = ExactNum::parse(bits, Radix::Bin, 512, RoundingMode::None, &mut cc);
        let got = ten.rem_pi(p, rm, &mut cc);
        if got != want {
            bad.push(format!("p={p} {name}: got {got:?}, want {bits}"));
        }
    }
    if bad.is_empty() {
        Ok(())
    } else {
        Err(format!("{} of {} rows differ:\n{}", bad.len(), REF.len(), bad.join("\n")))
    }
}
