//! Accuracy class of each public numeric function.
//!
//! The class is a documentation contract. It does not change rounding.
//! `tests/accuracy_table.rs` fails when a public numeric function is missing
//! or its rustdoc line disagrees with this table.

use alloc::format;
use alloc::string::String;

/// How far a public numeric function promises to agree with the true value.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Accuracy {
    /// Limb-identical to the correctly rounded result, in every rounding mode.
    CorrectlyRounded,
    /// At most one ulp from the correctly rounded result.
    Faithful,
    /// At most `lost_bits` away from the true value. The rustdoc states the number.
    WorkingPrecision {
        /// Bits the result may lose relative to a full-word rounding.
        lost_bits: u32,
    },
    /// The returned radius or error field contains the true value.
    ///
    /// `Ball` radii and `GkResult::abs_err_est` are enclosures. The
    /// Gauss–Kronrod field bounds the true error of the rounded estimate.
    Enclosure,
    /// Returns in time, stays in the documented domain, and has the right sign
    /// and at least two correct decimal digits. Not a rounding promise.
    Unspecified,
}

impl Accuracy {
    /// The rustdoc sentence this class requires.
    pub fn doc_line(self) -> String {
        match self {
            Accuracy::CorrectlyRounded => String::from("Accuracy: correctly-rounded"),
            Accuracy::Faithful => String::from("Accuracy: faithful"),
            Accuracy::WorkingPrecision { lost_bits } => {
                format!("Accuracy: working-precision, {lost_bits} bits")
            }
            Accuracy::Enclosure => String::from("Accuracy: enclosure"),
            Accuracy::Unspecified => String::from("Accuracy: unspecified"),
        }
    }
}

